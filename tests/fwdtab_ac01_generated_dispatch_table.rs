//! PRD-mcphost-generated-dispatch-table-stack-budget
//! AC1 — Given mcphost main containing PR #413, When
//! `scripts/gen-dispatch-table.sh --write` runs and then `--check` runs inside
//! `regen-check`'s generator list, Then `src/dispatch_table.rs` exists with one
//! sorted row per canonical dotted `host.*` verb of `mcphost contract dump`
//! minus `tool_aliases`, each row naming `arm_<verb>`, `--check` exits 0 on a
//! clean tree and 1 naming the stale file after any registry change without a
//! regen.

use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const MCPHOST: &str = env!("CARGO_BIN_EXE_mcphost");

fn repo() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn check_in(root: &Path) -> Output {
    Command::new("bash")
        .arg(root.join("scripts/gen-dispatch-table.sh"))
        .arg("--check")
        .env("MCPHOST_BIN", MCPHOST)
        .output()
        .expect("run gen-dispatch-table.sh")
}

/// The canonical dotted `host.*` verbs of `mcphost contract dump`.
fn registry_verbs(scratch: &Path) -> Vec<String> {
    let path = scratch.join("contract.json");
    let status = Command::new(MCPHOST)
        .args(["contract", "dump", "--path"])
        .arg(&path)
        .output()
        .expect("contract dump");
    assert!(status.status.success(), "contract dump failed: {status:?}");
    let doc: Value = serde_json::from_slice(&std::fs::read(&path).expect("read dump")).expect("dump is JSON");
    let mut verbs: Vec<String> = doc["tools"]
        .as_array()
        .expect("tools")
        .iter()
        .filter(|t| t.get("alias_of").is_none())
        .filter_map(|t| t["name"].as_str())
        .filter(|n| n.starts_with("host.") && mcphost::tool_aliases::resolve(n).is_none())
        .map(str::to_string)
        .collect();
    verbs.sort();
    verbs
}

fn scratch_dir(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("fwdtab-ac01-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("scratch dir");
    dir
}

#[test]
fn fwdtab_ac01_table_has_one_sorted_row_per_registry_verb() {
    let scratch = scratch_dir("rows");
    let verbs = registry_verbs(&scratch);
    let table = std::fs::read_to_string(repo().join("src/dispatch_table.rs")).expect("src/dispatch_table.rs exists");
    assert!(
        table.lines().take_while(|l| l.starts_with("//!") || l.is_empty()).count() > 0
            && table.lines().find(|l| !l.starts_with("//!") && !l.is_empty()).is_some_and(|l| l.starts_with("// GENERATED by scripts/gen-dispatch-table.sh")),
        "header names the generator"
    );
    let rows: Vec<(String, String)> = table
        .lines()
        .filter_map(|l| l.trim().strip_prefix("(\""))
        .filter_map(|l| l.split_once("\", McpHostHandler::"))
        .map(|(verb, f)| (verb.to_string(), f.trim_end_matches("),").to_string()))
        .collect();
    let names: Vec<String> = rows.iter().map(|(v, _)| v.clone()).collect();
    assert_eq!(names, verbs, "rows are exactly the registry's canonical dotted host.* verbs, sorted");
    for (verb, func) in &rows {
        assert_eq!(func, &format!("arm_{}", verb.replace('.', "_")), "row {verb} names its arm_ function");
    }
    let _ = std::fs::remove_dir_all(&scratch);
}

#[test]
fn fwdtab_ac01_check_passes_clean_and_names_the_stale_file() {
    let out = check_in(&repo());
    assert!(out.status.success(), "--check on the clean tree: {}", String::from_utf8_lossy(&out.stderr));

    // A tree whose table lacks a verb the registry advertises (a registry change
    // without a regen): the same script, run in a scratch copy of the layout.
    let scratch = scratch_dir("stale");
    std::fs::create_dir_all(scratch.join("scripts")).expect("scripts dir");
    std::fs::create_dir_all(scratch.join("src")).expect("src dir");
    std::fs::copy(repo().join("scripts/gen-dispatch-table.sh"), scratch.join("scripts/gen-dispatch-table.sh"))
        .expect("copy script");
    let table = std::fs::read_to_string(repo().join("src/dispatch_table.rs")).expect("table");
    let stale: String = table
        .lines()
        .filter(|l| !l.contains("(\"host.whoami\","))
        .map(|l| format!("{l}\n"))
        .collect();
    assert_ne!(stale, table, "the fixture removed the host.whoami row");
    std::fs::write(scratch.join("src/dispatch_table.rs"), stale).expect("write stale table");
    let out = check_in(&scratch);
    assert_eq!(out.status.code(), Some(1), "stale table exits 1: {out:?}");
    assert!(
        String::from_utf8_lossy(&out.stderr).contains("src/dispatch_table.rs is stale"),
        "names the stale file: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let _ = std::fs::remove_dir_all(&scratch);
}

#[test]
fn fwdtab_ac01_regen_check_runs_the_generator() {
    let ci = std::fs::read_to_string(repo().join(".github/workflows/ci.yml")).expect("ci.yml");
    assert!(
        ci.contains("check ./scripts/gen-dispatch-table.sh --check"),
        "regen-check's generator list runs gen-dispatch-table.sh --check"
    );
}
