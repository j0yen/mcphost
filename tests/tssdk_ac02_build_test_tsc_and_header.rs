//! PRD-mcphost-typescript-sdk-generated AC2 (P0) -- Given the generated
//! package, When `npm run build && npm test && tsc --strict --noEmit` run,
//! Then all exit 0 and every file under `src/` carries the generated-from
//! header with `1.<sha12>`.

use crate::tssdk;

#[test]
fn tssdk_ac02_build_test_and_tsc_pass_and_every_file_has_the_header() {
    let sha = mcphost::api_contract::sha_hex(mcphost::call_cli::EMBEDDED_CONTRACT);
    let header = format!("// generated by mcphost gen sdk ts from contract 1.{} -- do not edit", &sha[..12]);
    let files = tssdk::package_files(&tssdk::sdk_dir().join("src"));
    assert!(files.len() >= 6, "expected the full package, got {files:?}");
    for f in &files {
        let first = std::fs::read_to_string(f).unwrap().lines().next().unwrap_or_default().to_string();
        assert_eq!(first, header, "{} lacks the generated-from header", f.display());
    }

    tssdk::npm_ok(&["run", "build"]);
    tssdk::npm_ok(&["test"]);
    let tsc = tssdk::npm(&["exec", "--", "tsc", "--strict", "--noEmit"]);
    assert!(tsc.status.success(), "tsc --strict --noEmit failed:\n{}", tssdk::text(&tsc));
}
