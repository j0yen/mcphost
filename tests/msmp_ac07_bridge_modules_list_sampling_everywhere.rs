//! PRD-mcphost-sampling-from-tools
//! AC7 (P0) — Given `BRIDGE_MODULES`, When `unknown_import_hint()` and
//! `docs/sandbox-api.md` are rendered, Then both list `mcphost.sampling` and
//! the `runner_script_registered_modules` test passes.

use mcphost::kinds::python::{
    BRIDGE_DOCS_END, BRIDGE_DOCS_START, BRIDGE_MODULES, render_bridge_docs_block, runner_script_registered_modules,
    unknown_import_hint,
};
use std::collections::BTreeSet;

#[test]
fn hint_docs_and_runner_script_all_list_the_sampling_module() {
    let hint = unknown_import_hint();
    assert!(hint.contains("mcphost.sampling"), "unknown_import_hint must list mcphost.sampling: {hint}");

    let docs = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/docs/sandbox-api.md")).expect("read docs");
    let start = docs.find(BRIDGE_DOCS_START).expect("docs/sandbox-api.md carries the bridge-modules start marker");
    let end = docs.find(BRIDGE_DOCS_END).expect("docs/sandbox-api.md carries the bridge-modules end marker") + BRIDGE_DOCS_END.len();
    let block = &docs[start..end];
    assert_eq!(block, render_bridge_docs_block(), "the docs block must be exactly what BRIDGE_MODULES renders");
    assert!(block.contains("`mcphost.sampling`"), "the docs block must list mcphost.sampling: {block}");

    // The independent half of the contract: the runner script registers exactly these modules.
    let registered: BTreeSet<String> = runner_script_registered_modules().into_iter().collect();
    assert!(registered.contains("sampling"), "the runner script must register mcphost.sampling: {registered:?}");
    let declared: BTreeSet<String> = BRIDGE_MODULES.iter().map(|m| m.name.to_string()).collect();
    assert_eq!(registered, declared, "BRIDGE_MODULES and the runner script's sys.modules lines must not drift");
}

// Seed SDB: the block is GENERATED by scripts/sandbox-api-doc-check.sh --write,
// so a new BRIDGE_MODULES entry never leaves docs/sandbox-api.md stale.
fn run_doc_check(doc: &std::path::Path, args: &[&str]) -> std::process::Output {
    std::process::Command::new("bash")
        .arg(concat!(env!("CARGO_MANIFEST_DIR"), "/scripts/sandbox-api-doc-check.sh"))
        .args(args)
        .env("MCPHOST_BIN", env!("CARGO_BIN_EXE_mcphost"))
        .env("MCPHOST_SANDBOX_DOC", doc)
        .output()
        .expect("run sandbox-api-doc-check.sh")
}

fn stale_doc_copy(name: &str) -> (std::path::PathBuf, String) {
    let real = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/docs/sandbox-api.md")).expect("read docs");
    let start = real.find(BRIDGE_DOCS_START).unwrap();
    let end = real.find(BRIDGE_DOCS_END).unwrap() + BRIDGE_DOCS_END.len();
    let stale = format!("{}{BRIDGE_DOCS_START}\n- `mcphost.state` -- stale\n{BRIDGE_DOCS_END}{}", &real[..start], &real[end..]);
    assert_ne!(stale, real);
    let dir = std::env::temp_dir().join(format!("msmp_ac07_{}_{name}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let p = dir.join("sandbox-api.md");
    std::fs::write(&p, &stale).unwrap();
    (p, real)
}

#[test]
fn doc_check_write_regenerates_a_stale_bridge_block() {
    let (p, real) = stale_doc_copy("write");
    let out = run_doc_check(&p, &["--write-bridge"]);
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    let after = std::fs::read_to_string(&p).unwrap();
    let start = after.find(BRIDGE_DOCS_START).unwrap();
    let end = after.find(BRIDGE_DOCS_END).unwrap() + BRIDGE_DOCS_END.len();
    assert_eq!(&after[start..end], render_bridge_docs_block(), "--write must restore the rendered block");
    assert_eq!(after, real, "everything outside the block is left untouched");
}

#[test]
fn doc_check_check_mode_names_a_stale_bridge_block() {
    let (p, _) = stale_doc_copy("check");
    let out = run_doc_check(&p, &[]);
    assert!(!out.status.success(), "a stale bridge block must fail check mode");
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(err.contains("bridge-modules block differs"), "check mode names the bridge drift: {err}");
}
