// AC2: the generated package builds, and every file under src/ names the contract it came from.
import { readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

import { CONTRACT_SHA, CONTRACT_VERSION, Client } from "../src/index.js";

const srcDir = fileURLToPath(new URL("../src/", import.meta.url));

describe("generated package", () => {
  it("stamps 1.<sha12> as the contract version", () => {
    expect(CONTRACT_SHA).toMatch(/^[0-9a-f]{64}$/);
    expect(CONTRACT_VERSION).toBe(`1.${CONTRACT_SHA.slice(0, 12)}`);
  });

  it("opens every file under src/ with the generated-from header", () => {
    const files = readdirSync(srcDir).filter((f) => f.endsWith(".ts"));
    expect(files.length).toBeGreaterThanOrEqual(6);
    for (const f of files) {
      const first = readFileSync(srcDir + f, "utf8").split("\n")[0];
      expect(first, f).toBe(`// generated by mcphost gen sdk ts from contract ${CONTRACT_VERSION} -- do not edit`);
    }
  });

  it("exposes tools through family namespaces", () => {
    const c = new Client({ url: "http://host.test", onSkew: "ignore" });
    expect(typeof c.host.tool.publish).toBe("function");
    expect(typeof c.host.quickstart).toBe("function");
  });
});
