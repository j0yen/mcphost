// ---- request validation ---------------------------------------------------

fn valid_name(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else { return false };
    name.len() <= 64
        && (first.is_ascii_lowercase() || first.is_ascii_digit())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '-')
}

/// One validated source, ready to insert.
struct SourceSpec {
    kind: IndexSourceKind,
    reference: String,
    spec: Value,
}

/// A loopback-hosted instance (local dev, the test harness) may fetch
/// loopback urls; every real deployment keeps them refused. The instance's
/// own domain is always refused (`mcphost.dev` fetching itself).
fn url_policy(state: &AppState) -> (String, bool) {
    let own_host = reqwest::Url::parse(&state.public_url)
        .ok()
        .and_then(|u| u.host_str().map(str::to_string))
        .unwrap_or_default();
    let loopback = own_host == "localhost"
        || own_host.parse::<std::net::IpAddr>().is_ok_and(|ip| ip.is_loopback());
    if loopback { (String::new(), true) } else { (own_host, false) }
}

fn check_url(state: &AppState, raw: &str) -> Result<(), AppError> {
    let url = reqwest::Url::parse(raw).map_err(|e| invalid(format!("source url is not a valid url: {e}")))?;
    if !matches!(url.scheme(), "http" | "https") {
        return Err(invalid("source url must be http or https"));
    }
    let host = url.host_str().ok_or_else(|| invalid("source url has no host"))?;
    let (own_domain, allow_loopback) = url_policy(state);
    if crate::kinds::http::is_disallowed_literal_host(host, &own_domain, allow_loopback) {
        return Err(host_not_allowed(host));
    }
    Ok(())
}

async fn validate_source(
    state: &AppState,
    tenant: &Tenant,
    i: usize,
    raw: &Value,
) -> Result<SourceSpec, AppError> {
    let obj = raw.as_object().ok_or_else(|| invalid(format!("sources[{i}] must be an object")))?;
    let kind = obj
        .get("kind")
        .and_then(Value::as_str)
        .and_then(IndexSourceKind::parse)
        .ok_or_else(|| invalid(kinds_message()))?;
    match kind {
        IndexSourceKind::Doc => {
            let prefix = match obj.get("prefix") {
                None => String::new(),
                Some(Value::String(s)) => s.clone(),
                Some(_) => return Err(invalid(format!("sources[{i}].prefix must be a string"))),
            };
            Ok(SourceSpec { kind, reference: prefix.clone(), spec: json!({"kind": "doc", "prefix": prefix}) })
        }
        IndexSourceKind::Table => {
            let table = obj
                .get("table")
                .and_then(Value::as_str)
                .ok_or_else(|| invalid(format!("sources[{i}].table is required for a table source")))?
                .to_string();
            let columns: Vec<String> = obj
                .get("columns")
                .and_then(Value::as_array)
                .map(|a| a.iter().filter_map(|v| v.as_str().map(str::to_string)).collect())
                .unwrap_or_default();
            if columns.is_empty() || columns.len() > COLUMNS_MAX {
                return Err(invalid(format!(
                    "sources[{i}].columns must name 1-{COLUMNS_MAX} column names"
                )));
            }
            let path = crate::tables::tenant_db_path(state, tenant.id);
            let (t, cols) = (table.clone(), columns.clone());
            crate::tables::with_tenant_conn(path, state.db.cfg(), state.db.counters_handle(), move |conn| {
                let schema = crate::tables::load_schema_sync(conn, &t)?;
                for c in &cols {
                    if !schema.columns.contains_key(c) {
                        return Err(invalid(format!("table '{t}' has no column '{c}'")));
                    }
                }
                Ok(())
            })
            .await?;
            Ok(SourceSpec {
                kind,
                reference: table.clone(),
                spec: json!({"kind": "table", "table": table, "columns": columns}),
            })
        }
        IndexSourceKind::Url => {
            let url = obj
                .get("url")
                .and_then(Value::as_str)
                .ok_or_else(|| invalid(format!("sources[{i}].url is required for a url source")))?
                .to_string();
            check_url(state, &url)?;
            Ok(SourceSpec { kind, reference: url.clone(), spec: json!({"kind": "url", "url": url}) })
        }
    }
}

// ---- host.index.create ----------------------------------------------------

/// R1: registers the index and its sources; the build happens on the
/// scheduler, never here.
pub async fn index_create(state: &AppState, tenant: &Tenant, args: &Value) -> Result<Value, AppError> {
    let name = args
        .get("name")
        .and_then(Value::as_str)
        .ok_or_else(|| invalid("missing required argument 'name'"))?
        .to_string();
    if !valid_name(&name) {
        return Err(invalid("name must match ^[a-z0-9][a-z0-9_-]{0,63}$"));
    }
    let raw_sources = args
        .get("sources")
        .and_then(Value::as_array)
        .filter(|a| !a.is_empty() && a.len() <= SOURCES_MAX)
        .ok_or_else(|| invalid(format!("sources must be an array of 1-{SOURCES_MAX} source objects")))?;
    let chunking = args.get("chunking");
    let max_chars = chunking.and_then(|c| c.get("max_chars")).and_then(Value::as_i64).unwrap_or(DEFAULT_MAX_CHARS);
    let overlap = chunking
        .and_then(|c| c.get("overlap_chars"))
        .and_then(Value::as_i64)
        .unwrap_or(DEFAULT_OVERLAP_CHARS);
    if !MAX_CHARS_RANGE.contains(&max_chars) || overlap < 0 || overlap >= max_chars {
        return Err(invalid(format!(
            "chunking.max_chars must be {}-{} and chunking.overlap_chars 0 up to max_chars - 1",
            MAX_CHARS_RANGE.start(),
            MAX_CHARS_RANGE.end()
        )));
    }

    let mut specs = Vec::with_capacity(raw_sources.len());
    for (i, raw) in raw_sources.iter().enumerate() {
        specs.push(validate_source(state, tenant, i, raw).await?);
    }

    let plan = state.plans.get(&tenant.plan).ok_or_else(|| {
        AppError::Internal(format!("tenant's plan '{}' is not in the loaded plan catalog", tenant.plan))
    })?;
    let index_max = plan.index_max;
    let n_sources = specs.len();
    let tenant_id = tenant.id;
    let now = crate::state::now_unix();
    let name_c = name.clone();
    state
        .db
        .with_conn(move |conn| {
            conn.execute("BEGIN IMMEDIATE", [])?;
            let outcome: Result<(), AppError> = (|| {
                let exists: Option<i64> = conn
                    .query_row(
                        "SELECT id FROM indexes WHERE tenant_id = ?1 AND name = ?2",
                        params![tenant_id, name_c],
                        |r| r.get(0),
                    )
                    .optional()?;
                if exists.is_some() {
                    return Err(index_exists(&name_c));
                }
                let used: i64 = conn.query_row(
                    "SELECT COUNT(*) FROM indexes WHERE tenant_id = ?1",
                    params![tenant_id],
                    |r| r.get(0),
                )?;
                if used >= index_max {
                    return Err(quota_index_max(index_max, used));
                }
                conn.execute(
                    "INSERT INTO indexes (tenant_id, name, max_chars, overlap_chars, created_at) \
                     VALUES (?1, ?2, ?3, ?4, ?5)",
                    params![tenant_id, name_c, max_chars, overlap, now],
                )?;
                let index_id = conn.last_insert_rowid();
                for (pos, s) in specs.iter().enumerate() {
                    conn.execute(
                        "INSERT INTO index_sources \
                             (index_id, tenant_id, position, kind, ref, spec_json, updated_at) \
                         VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)",
                        params![
                            index_id,
                            tenant_id,
                            pos as i64,
                            s.kind.as_str(),
                            s.reference,
                            s.spec.to_string(),
                            now
                        ],
                    )?;
                }
                Ok(())
            })();
            match outcome {
                Ok(()) => conn.execute("COMMIT", []).map(|_| ()).map_err(AppError::from),
                Err(e) => {
                    let _ = conn.execute("ROLLBACK", []);
                    Err(e)
                }
            }
        })
        .await?;
    Ok(json!({"name": name, "sources": n_sources, "status": "building"}))
}

// ---- host.index.status ----------------------------------------------------

/// R4: `{name, chunks, pending, lag_seconds, quota: {index_chunks_max},
/// sources: [{kind, ref, items, chunks, last_error?}]}`.
pub async fn index_status(state: &AppState, tenant: &Tenant, args: &Value) -> Result<Value, AppError> {
    let name = args
        .get("name")
        .and_then(Value::as_str)
        .ok_or_else(|| invalid("missing required argument 'name'"))?
        .to_string();
    let plan = state.plans.get(&tenant.plan).ok_or_else(|| {
        AppError::Internal(format!("tenant's plan '{}' is not in the loaded plan catalog", tenant.plan))
    })?;
    let tenant_id = tenant.id;
    let name_c = name.clone();
    let (created_at, sources) = state
        .db
        .with_conn(move |conn| {
            let row: Option<(i64, i64)> = conn
                .query_row(
                    "SELECT id, created_at FROM indexes WHERE tenant_id = ?1 AND name = ?2",
                    params![tenant_id, name_c],
                    |r| Ok((r.get(0)?, r.get(1)?)),
                )
                .optional()?;
            let (index_id, created_at) = row.ok_or_else(|| index_not_found(&name_c))?;
            let mut stmt = conn.prepare(
                "SELECT kind, ref, state, items, \
                        (SELECT COUNT(*) FROM index_chunks c WHERE c.source_id = index_sources.id), \
                        last_error \
                 FROM index_sources WHERE index_id = ?1 ORDER BY position",
            )?;
            let rows = stmt
                .query_map(params![index_id], |r| {
                    Ok((
                        r.get::<_, String>(0)?,
                        r.get::<_, String>(1)?,
                        r.get::<_, String>(2)?,
                        r.get::<_, i64>(3)?,
                        r.get::<_, i64>(4)?,
                        r.get::<_, Option<String>>(5)?,
                    ))
                })?
                .collect::<Result<Vec<_>, _>>()?;
            Ok((created_at, rows))
        })
        .await?;

    let pending = sources.iter().filter(|s| s.2 == "pending").count() as i64;
    let chunks: i64 = sources.iter().map(|s| s.4).sum();
    let now = crate::state::now_unix();
    let lag_seconds = crate::docs::lag_seconds_since((pending > 0).then_some(created_at), now);
    let rows: Vec<Value> = sources
        .into_iter()
        .map(|(kind, reference, _, items, chunks, last_error)| {
            let mut o = json!({"kind": kind, "ref": reference, "items": items, "chunks": chunks});
            if let Some(e) = last_error {
                o["last_error"] = json!(e);
            }
            o
        })
        .collect();
    Ok(json!({
        "name": name,
        "chunks": chunks,
        "pending": pending,
        "lag_seconds": lag_seconds,
        "quota": {"index_chunks_max": plan.index_chunks_max},
        "sources": rows,
    }))
}

