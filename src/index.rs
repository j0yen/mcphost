//! Named indexes over mixed sources (PRD-mcphost-index-create-from-sources):
//! `host.index.create {name, sources[], chunking?}` registers an index and
//! returns at once; the 10 s scheduler in [`crate::docs_index`] then calls
//! [`tick_tenant`], which chunks every pending source into `index_chunks`
//! (byte offsets kept, lexical only -- the `vector` column stays NULL);
//! `host.index.status {name}` reports the counts.
//!
//! [`IndexSourceKind`] is the only list of source kinds: the tool schema's
//! `sources[].kind` enum ([`sources_schema`]), the `args_invalid` message
//! ([`kinds_list`]) and `docs/retrieval.md` ([`render_retrieval_doc`]) are
//! all generated from it, and a drift test asserts they cannot separate.

use std::time::Duration;

use rusqlite::{OptionalExtension, params};
use serde_json::{Value, json};

use crate::db::Tenant;
use crate::docs_index::{Chunk, chunk_text_with};
use crate::errors::AppError;
use crate::state::AppState;

/// R1: the default chunking window and overlap, in bytes.
pub const DEFAULT_MAX_CHARS: i64 = 1200;
pub const DEFAULT_OVERLAP_CHARS: i64 = 200;
/// Bounds a caller-supplied `chunking` must stay inside (overlap < max).
const MAX_CHARS_RANGE: std::ops::RangeInclusive<i64> = 50..=20_000;
/// R3: items (documents, table rows) one source consumes per tick.
pub const ITEMS_PER_TICK: i64 = 50;
/// R3: the largest URL body read, in bytes.
pub const URL_MAX_BYTES: usize = 2 * 1024 * 1024;
/// Technical considerations: a slow URL source must not stall the pass.
pub const URL_TIMEOUT: Duration = Duration::from_secs(10);
/// Redirect hops followed by hand (each hop is re-checked).
const URL_MAX_REDIRECTS: usize = 3;
/// Most sources one index may name.
pub const SOURCES_MAX: usize = 20;
/// R4: a url source's `refresh_s` when the caller names none, floored by
/// the plan's `schedule_min_interval_s`.
pub const DEFAULT_URL_REFRESH_S: i64 = 3600;
/// R6: consecutive url failures that pause the source.
pub const URL_FAIL_LIMIT: i64 = 3;
/// Most columns one table source may name.
const COLUMNS_MAX: usize = 16;

/// R2: the only list of source kinds.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IndexSourceKind {
    Doc,
    Table,
    Url,
}

impl IndexSourceKind {
    pub const ALL: [IndexSourceKind; 3] =
        [IndexSourceKind::Doc, IndexSourceKind::Table, IndexSourceKind::Url];

    pub fn as_str(self) -> &'static str {
        match self {
            IndexSourceKind::Doc => "doc",
            IndexSourceKind::Table => "table",
            IndexSourceKind::Url => "url",
        }
    }

    pub fn parse(s: &str) -> Option<IndexSourceKind> {
        Self::ALL.into_iter().find(|k| k.as_str() == s)
    }

    pub fn names() -> Vec<&'static str> {
        Self::ALL.iter().map(|k| k.as_str()).collect()
    }
}

/// `doc, table, url` -- the list the `args_invalid` message and the docs
/// carry.
pub fn kinds_list() -> String {
    IndexSourceKind::names().join(", ")
}

/// The `sources` property of `host.index.create`'s input schema, its
/// `kind` enum generated from [`IndexSourceKind`].
pub fn sources_schema() -> Value {
    json!({
        "type": "array",
        "description": format!(
            "What to index, one object per source; kind is one of: {}. doc: {{prefix}} indexes \
             this tenant's documents whose name starts with prefix; table: {{table, columns}} \
             indexes the named text columns of a host.table table, one chunk set per row; url: \
             {{url}} fetches one public http(s) page (2 MiB cap).",
            kinds_list()
        ),
        "items": {
            "type": "object",
            "properties": {
                "kind": {"type": "string", "enum": IndexSourceKind::names()},
                "prefix": {"type": "string", "description": "doc: document-name prefix."},
                "table": {"type": "string", "description": "table: a host.table table name."},
                "columns": {"type": "array", "items": {"type": "string"}, "description": "table: the columns whose text to index."},
                "url": {"type": "string", "description": "url: the page to fetch."},
                "refresh_s": {"type": "integer", "description": "url: seconds between looks at the page (default 3600; the plan's schedule floor is the minimum, free 300)."},
            },
            "required": ["kind"],
        },
    })
}

/// R2: `docs/retrieval.md`, rendered from [`IndexSourceKind`].
pub fn render_retrieval_doc() -> String {
    let mut out = String::new();
    out.push_str("# Retrieval: named indexes\n\n");
    out.push_str(
        "<!-- generated by `mcphost gen-docs` from `index::IndexSourceKind`; do not edit by hand -->\n\n",
    );
    out.push_str(
        "`host.index.create {name, sources[], chunking?}` registers a named index and returns \
         at once; the background indexer chunks every source into one chunk table with byte \
         offsets. `host.index.status {name}` reports `chunks`, `pending`, `lag_seconds` and \
         per-source counts.\n\n",
    );
    out.push_str("## Source kinds\n\n");
    out.push_str("<!-- kinds:start -->\n");
    for k in IndexSourceKind::ALL {
        out.push_str(&format!("- `{}`: {}\n", k.as_str(), kind_blurb(k)));
    }
    out.push_str("<!-- kinds:end -->\n\n");
    out.push_str(&format!(
        "An unknown `kind` is refused `args_invalid` with the message `{}`.\n\n",
        kinds_message()
    ));
    out.push_str("## Freshness\n\n");
    out.push_str(
        "Every source carries a change marker: the document watermark for `doc`, a per-table \
         write counter for `table`, the `ETag` / `Last-Modified` for `url`. The background \
         indexer re-chunks only what moved and keeps the vector of any chunk whose text is \
         unchanged. `host.index.status` and `host.index.query` carry `stale_sources: [{ref, \
         behind_by, since_s}]`, empty when the index is current. A `url` source is looked at \
         every `refresh_s` seconds (default 3600; below the plan's schedule floor, free 300, is \
         `args_invalid` with `data.minimum`); three failures in a row pause it until `host.index.refresh` names it.\n\n",
    );
    out.push_str("## Limits\n\n");
    out.push_str(
        "`host.quickstart` `limits.plan` carries `index_max` (indexes per tenant, refused \
         `quota_index_max`) and `index_chunks_max` (chunks per tenant; a build past it \
         truncates the source and sets `last_error: \"quota_index_chunks_max\"`).\n",
    );
    out
}

fn kind_blurb(k: IndexSourceKind) -> &'static str {
    match k {
        IndexSourceKind::Doc => "documents whose name starts with `prefix`",
        IndexSourceKind::Table => "the text `columns` of a `table`, one item per row",
        IndexSourceKind::Url => "one public http(s) `url`, up to 2 MiB",
    }
}

/// The `args_invalid` message for an unknown kind.
pub fn kinds_message() -> String {
    format!("source kind must be one of: {}", kinds_list())
}

