//! PRD-mcphost-examples-gallery-page: the examples surfaces rendered from the
//! embedded index -- the `## Examples` section of `www/llms.txt` (generated
//! by `mcphost examples index`, drift-tested), and the `/examples` routes.
//! Every string is derived from the manifests; nothing here restates an
//! example.

use crate::examples::{Example, IndexEntry};

pub const EXAMPLES_SECTION_START: &str = "<!-- examples begin -->";
pub const EXAMPLES_SECTION_END: &str = "<!-- examples end -->";

/// The one call that forks example `name` (what a card and an llms row show).
pub fn fork_snippet(name: &str) -> String {
    format!("host.example.fork {{\"name\": \"{name}\"}}")
}

/// What one llms.txt row is built from; both the on-disk manifests
/// ([`IndexEntry`]) and the compiled-in index ([`Example`]) convert to it.
pub struct SectionRow {
    pub name: String,
    pub title: String,
    pub tags: Vec<String>,
    pub secrets: usize,
}

impl From<&IndexEntry> for SectionRow {
    fn from(e: &IndexEntry) -> Self {
        Self { name: e.name.clone(), title: e.title.clone(), tags: e.use_case.clone(), secrets: e.secrets_needed.len() }
    }
}

impl From<&Example> for SectionRow {
    fn from(e: &Example) -> Self {
        Self {
            name: e.name.to_string(),
            title: e.title.to_string(),
            tags: e.use_case.iter().map(|t| t.to_string()).collect(),
            secrets: e.secrets_needed.len(),
        }
    }
}

/// The marked `## Examples` section: one line per example -- name, title,
/// tags, secrets count, fork snippet.
pub fn render_llms_section(rows: &[SectionRow]) -> String {
    let mut out = String::new();
    out.push_str(EXAMPLES_SECTION_START);
    out.push_str("\n## Examples\n\n");
    out.push_str(
        "Generated by `mcphost examples index` from `examples/*/example.toml`; do not hand-edit. \
         Pick the row that matches what you need and make the one call on it; the same rows, \
         with last night's proof status, are at `/examples.json`.\n\n",
    );
    for r in rows {
        out.push_str(&format!(
            "- {} — {} — tags: {} — secrets: {} — fork: {}\n",
            r.name,
            r.title,
            r.tags.join(", "),
            r.secrets,
            fork_snippet(&r.name),
        ));
    }
    out.push_str(EXAMPLES_SECTION_END);
    out
}

/// Replace the marked examples section in `content`, or -- before any marker
/// exists -- insert it just before the `## Full documentation` heading (else
/// append), so this never drops the section. Idempotent.
pub fn splice_llms_section(content: &str, section: &str) -> String {
    let section = section.trim_end();
    if let (Some(start), Some(end_pos)) =
        (content.find(EXAMPLES_SECTION_START), content.find(EXAMPLES_SECTION_END))
    {
        let end = end_pos + EXAMPLES_SECTION_END.len();
        format!("{}{}{}", &content[..start], section, &content[end..])
    } else if let Some(idx) = content.find("## Full documentation") {
        format!("{}{}\n\n{}", &content[..idx], section, &content[idx..])
    } else {
        format!("{}\n\n{}\n", content.trim_end(), section)
    }
}

/// `mcphost examples index`: rewrite the examples section of the llms.txt at
/// `path` from `entries`. A missing file is skipped (`Ok(false)`); returns
/// whether the file's bytes changed.
pub fn write_llms_section(path: &std::path::Path, entries: &[IndexEntry]) -> std::io::Result<bool> {
    let Ok(current) = std::fs::read_to_string(path) else { return Ok(false) };
    let rows: Vec<SectionRow> = entries.iter().map(SectionRow::from).collect();
    let next = splice_llms_section(&current, &render_llms_section(&rows));
    if next == current {
        return Ok(false);
    }
    std::fs::write(path, next)?;
    Ok(true)
}

