use std::collections::HashMap;

use crate::claim::html_escape as esc;
use crate::db::Db;

/// One `example_proofs` row (written by PRD-mcphost-example-proof-nightly-
/// and-hide). A row with a `hidden_reason` hides its example everywhere.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Proof {
    pub ok: bool,
    /// Text as stored; a unix-seconds integer is rendered as `YYYY-MM-DD`.
    pub at: Option<String>,
    pub log_excerpt: Option<String>,
    pub hidden_reason: Option<String>,
}

impl Proof {
    pub fn hidden(&self) -> bool {
        self.hidden_reason.as_deref().is_some_and(|r| !r.is_empty())
    }

    /// The date the badge shows.
    pub fn date(&self) -> Option<String> {
        let at = self.at.as_deref()?;
        match at.parse::<u64>() {
            Ok(secs) => Some(crate::docs_examples::civil_date(secs)),
            Err(_) => Some(at.chars().take(10).collect()),
        }
    }
}

/// Proof status by example name. A host without the `example_proofs` table
/// (older than the proof-runner PRD) or with an unreadable one yields an
/// empty map -- every example `unproven`, never an error.
pub async fn load_proofs(db: &Db) -> HashMap<String, Proof> {
    db.with_conn(|conn| {
        let has_table: bool = conn
            .query_row("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'example_proofs'", [], |_| Ok(true))
            .unwrap_or(false);
        if !has_table {
            return Ok(HashMap::new());
        }
        let mut stmt = conn.prepare("SELECT name, ok, at, log_excerpt, hidden_reason FROM example_proofs")?;
        let rows = stmt.query_map([], |r| {
            let text = |i: usize| -> rusqlite::Result<Option<String>> {
                Ok(match r.get_ref(i)? {
                    rusqlite::types::ValueRef::Null => None,
                    rusqlite::types::ValueRef::Integer(n) => Some(n.to_string()),
                    rusqlite::types::ValueRef::Real(f) => Some((f as i64).to_string()),
                    rusqlite::types::ValueRef::Text(t) | rusqlite::types::ValueRef::Blob(t) => {
                        Some(String::from_utf8_lossy(t).into_owned())
                    }
                })
            };
            Ok((r.get::<_, String>(0)?, Proof { ok: r.get::<_, i64>(1)? != 0, at: text(2)?, log_excerpt: text(3)?, hidden_reason: text(4)? }))
        })?;
        Ok(rows.filter_map(Result::ok).collect())
    })
    .await
    .unwrap_or_default()
}

// -------------------------------------------------------------------- page

fn page(title: &str, body: &str) -> String {
    format!(
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\
         <title>{}</title></head><body><main>{body}</main></body></html>\n",
        esc(title)
    )
}

fn badge(proof: Option<&Proof>) -> String {
    match proof.filter(|p| p.ok).and_then(Proof::date) {
        Some(d) => format!("proven {d}"),
        None => "unproven".to_string(),
    }
}

fn card(ex: &Example, proof: Option<&Proof>) -> String {
    let tools: Vec<&str> = ex.tools.iter().map(|t| t.name).collect();
    format!(
        "<article class=\"card\" id=\"{name}\">\
         <h2><a href=\"/examples/{name}\">{title}</a></h2>\
         <p class=\"badge\">{badge}</p>\
         <p>{summary}</p>\
         <p class=\"tags\">tags: {tags} · clients: {clients}</p>\
         <p class=\"tools\">tools: {tools} · secrets needed: {secrets}</p>\
         <pre class=\"fork\">{fork}</pre></article>\n",
        name = esc(ex.name),
        title = esc(ex.title),
        badge = esc(&badge(proof)),
        summary = esc(ex.summary),
        tags = esc(&ex.use_case.join(", ")),
        clients = esc(&ex.clients.join(", ")),
        tools = if tools.is_empty() { "none".to_string() } else { esc(&tools.join(", ")) },
        secrets = ex.secrets_needed.len(),
        fork = esc(&fork_snippet(ex.name)),
    )
}

/// `?use_case=` / `?client=` on `GET /examples`.
#[derive(Debug, Default, Clone)]
pub struct Filter {
    pub use_case: Option<String>,
    pub client: Option<String>,
}

impl Filter {
    /// An example passes when it carries the use-case tag, and its `clients`
    /// contain the client or `any`. An unknown tag matches nothing.
    pub fn matches(&self, ex: &Example) -> bool {
        self.use_case.as_deref().is_none_or(|t| ex.use_case.contains(&t))
            && self.client.as_deref().is_none_or(|c| ex.clients.iter().any(|x| *x == c || *x == "any"))
    }
}

/// `GET /examples`: one card per example in `examples` that passes `filter`,
/// server-rendered, above a list of every valid use-case tag.
pub fn render_index_page(examples: &[&Example], proofs: &HashMap<String, Proof>, filter: &Filter) -> String {
    let mut body = String::from("<h1>Examples</h1>\n<p>Each card is one working example; fork it with the one call shown.</p>\n");
    body.push_str("<nav class=\"use-cases\">use cases: ");
    body.push_str(
        &crate::examples::EXAMPLE_USE_CASES
            .iter()
            .map(|t| format!("<a href=\"/examples?use_case={t}\">{t}</a>", t = esc(t)))
            .collect::<Vec<_>>()
            .join(" · "),
    );
    body.push_str("</nav>\n");
    let shown: Vec<&&Example> = examples.iter().filter(|e| filter.matches(e)).collect();
    if shown.is_empty() {
        body.push_str("<p class=\"empty\">No examples match this filter.</p>\n");
    }
    for ex in shown {
        body.push_str(&card(ex, proofs.get(ex.name)));
    }
    page("mcphost examples", &body)
}

/// Examples a reader may see: everything the proof runner has not hidden.
pub fn visible<'a>(examples: &'a [Example], proofs: &HashMap<String, Proof>) -> Vec<&'a Example> {
    examples.iter().filter(|e| !proofs.get(e.name).is_some_and(Proof::hidden)).collect()
}

/// The `first_call` as the JSON-RPC body that makes it.
pub fn first_call_body(ex: &Example) -> serde_json::Value {
    let args = serde_json::from_str::<serde_json::Value>(ex.first_call.args_json).unwrap_or_else(|_| serde_json::json!({}));
    serde_json::json!({
        "jsonrpc": "2.0",
        "id": 1,
        "method": "tools/call",
        "params": {"name": ex.first_call.tool, "arguments": args},
    })
}

const LOG_EXCERPT_LINES: usize = 20;

/// `GET /examples/<name>` for a visible example.
pub fn render_detail_page(ex: &Example, proof: Option<&Proof>) -> String {
    let mut body = format!(
        "<h1>{}</h1>\n<p class=\"badge\">{}</p>\n<p>{}</p>\n<p><a href=\"/examples\">all examples</a></p>\n\
         <h2>Fork it</h2>\n<pre class=\"fork\">{}</pre>\n",
        esc(ex.title),
        esc(&badge(proof)),
        esc(ex.summary),
        esc(&fork_snippet(ex.name)),
    );
    body.push_str(&format!(
        "<p>tags: {} · clients: {} · since {}</p>\n",
        esc(&ex.use_case.join(", ")),
        esc(&ex.clients.join(", ")),
        esc(ex.since),
    ));
    body.push_str("<h2>Secrets needed</h2>\n");
    if ex.secrets_needed.is_empty() {
        body.push_str("<p>none</p>\n");
    } else {
        body.push_str(&format!("<ul>{}</ul>\n", ex.secrets_needed.iter().map(|s| format!("<li>{}</li>", esc(s))).collect::<String>()));
    }
    body.push_str("<h2>Tools</h2>\n");
    if ex.tools.is_empty() {
        body.push_str("<p>none: the first call uses a host tool.</p>\n");
    }
    for t in ex.tools {
        body.push_str(&format!(
            "<h3>{} <small>({}, {})</small></h3>\n<pre class=\"source\">{}</pre>\n",
            esc(t.name),
            esc(t.kind),
            esc(t.file),
            esc(t.source),
        ));
    }
    let call = serde_json::to_string_pretty(&first_call_body(ex)).unwrap_or_default();
    body.push_str(&format!(
        "<h2>First call</h2>\n<pre class=\"first-call\">{}</pre>\n<p>expect: <code>{}</code></p>\n",
        esc(&call),
        esc(ex.first_call.expect),
    ));
    body.push_str("<h2>Latest proof</h2>\n");
    match proof {
        Some(p) => {
            body.push_str(&format!(
                "<p>ok: {} · at: {}</p>\n",
                p.ok,
                esc(p.date().as_deref().unwrap_or("unknown")),
            ));
            if let Some(log) = p.log_excerpt.as_deref().filter(|l| !l.is_empty()) {
                let excerpt: Vec<&str> = log.lines().rev().take(LOG_EXCERPT_LINES).collect::<Vec<_>>().into_iter().rev().collect();
                body.push_str(&format!("<pre class=\"proof-log\">{}</pre>\n", esc(&excerpt.join("\n"))));
            }
        }
        None => body.push_str("<p>no proof recorded yet</p>\n"),
    }
    page(&format!("{} — mcphost examples", ex.title), &body)
}

/// The (up to) three visible names closest to `asked`.
pub fn nearest_names(asked: &str, visible: &[&Example]) -> Vec<&'static str> {
    let mut names: Vec<&'static str> = visible.iter().map(|e| e.name).collect();
    names.sort_by_key(|n| (crate::errors::levenshtein(asked, n), *n));
    names.truncate(3);
    names
}

/// `GET /examples/<name>` for an unknown or hidden name: the same page for
/// both, so a hidden example is indistinguishable from one that never was.
pub fn render_not_found(asked: &str, visible: &[&Example]) -> String {
    let items: String = nearest_names(asked, visible)
        .iter()
        .map(|n| format!("<li><a href=\"/examples/{n}\">{n}</a></li>", n = esc(n)))
        .collect();
    page(
        "no such example",
        &format!("<h1>No example named {}</h1>\n<p>Nearest names:</p>\n<ul class=\"nearest\">{items}</ul>\n<p><a href=\"/examples\">all examples</a></p>\n", esc(asked)),
    )
}

/// `GET /examples.json`: the index rows plus `proof: {ok, at, hidden_reason?}`.
/// Field names are the manifest's, except the manifest's `proof` (the script
/// path) is `proof_script` here so `proof` can carry the status. Hidden
/// examples are omitted unless `include_hidden` (the route requires admin).
pub fn examples_json(examples: &[Example], proofs: &HashMap<String, Proof>, include_hidden: bool) -> serde_json::Value {
    let rows: Vec<serde_json::Value> = examples
        .iter()
        .filter(|e| include_hidden || !proofs.get(e.name).is_some_and(Proof::hidden))
        .map(|e| {
            let mut proof = serde_json::Map::new();
            let p = proofs.get(e.name);
            proof.insert("ok".into(), serde_json::json!(p.map(|p| p.ok)));
            proof.insert("at".into(), serde_json::json!(p.and_then(Proof::date)));
            if let Some(reason) = p.and_then(|p| p.hidden_reason.as_deref()).filter(|r| !r.is_empty()) {
                proof.insert("hidden_reason".into(), serde_json::json!(reason));
            }
            serde_json::json!({
                "name": e.name,
                "title": e.title,
                "summary": e.summary,
                "use_case": e.use_case,
                "clients": e.clients,
                "since": e.since,
                "proof_script": e.proof,
                "secrets_needed": e.secrets_needed,
                "tools": e.tools.iter().map(|t| serde_json::json!({"name": t.name, "kind": t.kind, "file": t.file, "network": t.network})).collect::<Vec<_>>(),
                "first_call": {
                    "tool": e.first_call.tool,
                    "args": serde_json::from_str::<serde_json::Value>(e.first_call.args_json).unwrap_or_else(|_| serde_json::json!({})),
                    "expect": e.first_call.expect,
                },
                "fork": fork_snippet(e.name),
                "proof": proof,
            })
        })
        .collect();
    serde_json::json!({"generated_from": "examples/index.json", "examples": rows})
}

// ----------------------------------------------------------------- sitemap

const SITEMAP_ORIGIN: &str = "https://mcphost.dev";

/// R5: the `/examples` entry and one per example, between the same marker
/// pair the llms.txt section uses (XML comments).
pub fn render_sitemap_section(names: &[String]) -> String {
    let mut out = format!("  {EXAMPLES_SECTION_START}\n  <url><loc>{SITEMAP_ORIGIN}/examples</loc></url>\n");
    for n in names {
        out.push_str(&format!("  <url><loc>{SITEMAP_ORIGIN}/examples/{n}</loc></url>\n"));
    }
    out.push_str(&format!("  {EXAMPLES_SECTION_END}"));
    out
}

/// Replace the marked block in `sitemap`, or -- first run -- insert it before
/// `</urlset>`. Idempotent.
pub fn splice_sitemap_section(sitemap: &str, section: &str) -> String {
    let section = section.trim_end();
    if let (Some(start), Some(end_pos)) = (sitemap.find(EXAMPLES_SECTION_START), sitemap.find(EXAMPLES_SECTION_END)) {
        // Keep the leading indentation that sits before the start marker.
        let line_start = sitemap[..start].rfind('\n').map_or(0, |i| i + 1);
        let end = end_pos + EXAMPLES_SECTION_END.len();
        format!("{}{}{}", &sitemap[..line_start], section, &sitemap[end..])
    } else if let Some(idx) = sitemap.find("</urlset>") {
        format!("{}{}\n{}", &sitemap[..idx], section, &sitemap[idx..])
    } else {
        format!("{}\n{}\n", sitemap.trim_end(), section)
    }
}

/// `mcphost examples index`: rewrite the sitemap's examples block. Missing
/// file is skipped; returns whether the bytes changed.
pub fn write_sitemap_section(path: &std::path::Path, entries: &[IndexEntry]) -> std::io::Result<bool> {
    let Ok(current) = std::fs::read_to_string(path) else { return Ok(false) };
    let names: Vec<String> = entries.iter().map(|e| e.name.clone()).collect();
    let next = splice_sitemap_section(&current, &render_sitemap_section(&names));
    if next == current {
        return Ok(false);
    }
    std::fs::write(path, next)?;
    Ok(true)
}

/// First difference between the marked block of `committed` and `expected`,
/// naming the line; `Ok` when the block matches (anything outside the
/// markers is not looked at).
pub fn section_drift(committed: &str, expected: &str) -> Result<(), String> {
    let block = |s: &str| -> Option<Vec<String>> {
        let a = s.find(EXAMPLES_SECTION_START)?;
        let b = s.find(EXAMPLES_SECTION_END)? + EXAMPLES_SECTION_END.len();
        Some(s[a..b].lines().map(|l| l.trim().to_string()).collect())
    };
    let Some(have) = block(committed) else { return Err("no examples markers in the committed file".to_string()) };
    let want = block(expected).expect("rendered section carries its markers");
    for i in 0..have.len().max(want.len()) {
        let (h, w) = (have.get(i), want.get(i));
        if h != w {
            return Err(format!(
                "examples section line {} differs: committed `{}`, expected `{}` (run `mcphost examples index`)",
                i + 1,
                h.map_or("<missing>", |s| s.as_str()),
                w.map_or("<missing>", |s| s.as_str()),
            ));
        }
    }
    Ok(())
}
