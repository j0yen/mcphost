/// The schedule `host.sync.create` uses when `every` is omitted.
pub const DEFAULT_EVERY: &str = "*/15 * * * *";

/// No sync schedule fires more often than this.
pub const MIN_INTERVAL_SECS: i64 = 300;

/// How many successive firings [`check_interval`] compares.
const INTERVAL_SAMPLES: usize = 12;

crate::err_code! {
    pub SCHEDULE_TOO_FREQUENT,
    code: "schedule_too_frequent", family: Plan, class: AgentFault, retryable: false,
    remedy: "Use an `every` schedule that fires at most once every 5 minutes (data.min_seconds).",
}

crate::err_code! {
    pub QUOTA_SYNCS_MAX,
    code: "quota_syncs_max", family: Plan, class: PlanLimit, retryable: false,
    remedy: "Delete a sync with host.sync.delete or move to a plan with a higher syncs_max.",
}

