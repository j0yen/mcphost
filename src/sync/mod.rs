//! PRD-mcphost-sync-source-registry-and-create: `host.sync.*` registers a
//! scheduled mirror of an external dataset into a host table. [`SourceKind`]
//! is the one registry of source kinds; the tool schema's `source.kind` enum,
//! the `args_invalid` message, the sync-sources table in `docs/tools.md`, the
//! `## Data sync` section of `www/llms.txt` and the [`puller`] dispatch
//! `match` are all rendered or iterated from [`SourceKind::ALL`].

use serde_json::{Value, json};

use crate::db::Tenant;
use crate::errors::AppError;
use crate::state::AppState;

/// Every place an external dataset can be mirrored from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum SourceKind {
    CsvUrl,
    GoogleSheet,
    Airtable,
    NotionDb,
    HttpJson,
}

impl SourceKind {
    pub const ALL: &'static [SourceKind] = &[
        SourceKind::CsvUrl,
        SourceKind::GoogleSheet,
        SourceKind::Airtable,
        SourceKind::NotionDb,
        SourceKind::HttpJson,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            SourceKind::CsvUrl => "csv_url",
            SourceKind::GoogleSheet => "google_sheet",
            SourceKind::Airtable => "airtable",
            SourceKind::NotionDb => "notion_db",
            SourceKind::HttpJson => "http_json",
        }
    }

    pub fn parse(s: &str) -> Option<SourceKind> {
        Self::ALL.iter().copied().find(|k| k.as_str() == s)
    }

    /// The `host.connect` provider a kind pulls through, if any.
    pub fn needs_connection(self) -> Option<&'static str> {
        match self {
            SourceKind::GoogleSheet => Some("google"),
            SourceKind::Airtable => Some("airtable"),
            SourceKind::NotionDb => Some("notion"),
            SourceKind::CsvUrl | SourceKind::HttpJson => None,
        }
    }

    /// One line: what `source.ref` holds for this kind.
    pub fn ref_help(self) -> &'static str {
        match self {
            SourceKind::CsvUrl => "a public https URL that serves a CSV file",
            SourceKind::GoogleSheet => "a spreadsheet id, or spreadsheet id and tab as `<id>#<tab>`",
            SourceKind::Airtable => "a base and table as `<base_id>/<table_id>`",
            SourceKind::NotionDb => "a Notion database id",
            SourceKind::HttpJson => "a public https URL that serves a JSON array of objects",
        }
    }
}

/// `csv_url, google_sheet, ...` -- the list `args_invalid` messages carry.
pub fn kinds_csv() -> String {
    SourceKind::ALL.iter().map(|k| k.as_str()).collect::<Vec<_>>().join(", ")
}

/// The JSON-schema `enum` of `source.kind`.
pub fn kind_enum() -> Vec<&'static str> {
    SourceKind::ALL.iter().map(|k| k.as_str()).collect()
}

// ---- puller dispatch ----
/// The puller that fetches rows for a kind. The `match` has no wildcard arm,
/// so a kind added to [`SourceKind`] without a puller does not compile.
pub fn puller(kind: SourceKind) -> &'static str {
    match kind {
        SourceKind::CsvUrl => "http_csv",
        SourceKind::GoogleSheet => "google_sheets_api",
        SourceKind::Airtable => "airtable_api",
        SourceKind::NotionDb => "notion_api",
        SourceKind::HttpJson => "http_json",
    }
}
