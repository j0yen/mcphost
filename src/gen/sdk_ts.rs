//! PRD-mcphost-typescript-sdk-generated R1: `mcphost gen sdk ts` renders
//! `sdk/ts/src/` from `contracts/host-tools.v1.json`.
//!
//! One zod schema per canonical tool's args and result (`alias_of` entries
//! are skipped), one method per tool grouped into family namespaces by the
//! dotted name (`client.host.tool.publish({...})`), one error class per error
//! code. Rendering is deterministic (sorted, no timestamps) so CI can
//! regenerate and `diff -r` against the committed tree.
//!
//! Everything about a schema is read through [`super::schema_ir`], the reader
//! the Python generator shares. Anything the renderer has to special-case per
//! TOOL goes in [`OVERRIDES`]; the PRD's falsifier is that this table reaches
//! five entries. Per-construct rules (reserved-word and non-identifier
//! property names render string-keyed, `"null"` in a type list becomes
//! `.nullable()`, `allOf`/`if`/`then`/`anyOf` conditionals are server-side
//! validation and are not rendered) are generic and are not overrides.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde_json::Value;

use super::schema_ir::{self, Lit};

/// Default package root of `mcphost gen sdk ts` (the files land in `<out>/src`).
pub const DEFAULT_OUT: &str = "sdk/ts";

/// `(canonical tool, reason)` pairs the renderer special-cases. Empty: every
/// canonical tool renders through the generic rules. AC1 fails the premise at
/// five entries.
pub const OVERRIDES: &[(&str, &str)] = &[];

const RUNTIME_TS: &str = include_str!("sdk_ts_tmpl/runtime.ts");
const ERRORS_PRELUDE_TS: &str = include_str!("sdk_ts_tmpl/errors_prelude.ts");

/// Names `BaseClient` owns; a top-level family may not shadow them.
const CLIENT_MEMBERS: &[&str] = &["ready", "call", "contractSkew", "toString", "constructor"];

/// Where the error-code list came from, recorded in `errors.ts`'s header.
pub const ERROR_SOURCE: &str =
    "AppError::code() + feedback::CODE_TO_KIND + feedback::KIND_LEVEL_CODES + error_registry::ERROR_CODES (no /errors.json yet)";

const TS_RESERVED: &[&str] = &[
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
    "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
    "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
    "let", "static", "implements", "interface", "package", "private", "protected", "public", "await", "async",
];

/// The header every generated file starts with; `version` is `1.<sha12>`.
pub fn header(version: &str) -> String {
    format!("// generated by mcphost gen sdk ts from contract {version} -- do not edit\n")
}

fn js_str(s: &str) -> String {
    serde_json::to_string(s).expect("string serializes")
}

/// A property key: bare when it is a plain identifier, string-keyed otherwise
/// (including TS reserved words, which is a rule and not an override).
fn key(wire: &str) -> String {
    let ident = wire.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && wire.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ident && !TS_RESERVED.contains(&wire) { wire.to_string() } else { js_str(wire) }
}

/// `host.tool_publish` / `args_invalid` -> `HostToolPublish` / `ArgsInvalid`.
pub fn camel(s: &str) -> String {
    s.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut cs = p.chars();
            cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
        })
        .collect()
}

/// A JS identifier for a method / namespace segment of a tool name.
fn ident(seg: &str) -> String {
    let mut s: String = seg.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' || c == '$' { c } else { '_' }).collect();
    if s.is_empty() || s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, '_');
    }
    s
}

fn lit(l: &Lit) -> String {
    match l {
        Lit::Str(s) => js_str(s),
        Lit::Bool(b) => b.to_string(),
        Lit::Num(n) => n.clone(),
    }
}

/// The zod expression for `schema`; `args` selects `.strict()` for objects
/// that forbid extra properties (results always `.passthrough()`, R3).
pub fn zod(schema: &Value, args: bool) -> String {
    let (types, nullable) = schema_ir::schema_types(schema);
    let mut expr = if let Some((lits, _)) = schema_ir::enum_values(schema) {
        if lits.iter().all(|l| matches!(l, Lit::Str(_))) {
            format!("z.enum([{}])", lits.iter().map(lit).collect::<Vec<_>>().join(", "))
        } else if lits.len() == 1 {
            format!("z.literal({})", lit(&lits[0]))
        } else {
            format!("z.union([{}])", lits.iter().map(|l| format!("z.literal({})", lit(l))).collect::<Vec<_>>().join(", "))
        }
    } else {
        let alts: Vec<String> = types.iter().map(|t| zod_type(schema, t, args)).collect();
        match alts.len() {
            0 => "z.unknown()".to_string(),
            1 => alts.into_iter().next().unwrap_or_default(),
            _ => format!("z.union([{}])", alts.join(", ")),
        }
    };
    let nullable = nullable || schema_ir::enum_values(schema).is_some_and(|(_, n)| n);
    if nullable && expr != "z.unknown()" {
        expr.push_str(".nullable()");
    }
    expr
}

fn zod_type(schema: &Value, ty: &str, args: bool) -> String {
    let b = schema_ir::bounds(schema, ty);
    let mut out = match ty {
        "string" => "z.string()".to_string(),
        "integer" => "z.number().int()".to_string(),
        "number" => "z.number()".to_string(),
        "boolean" => "z.boolean()".to_string(),
        "array" => {
            let item = schema.get("items").cloned().unwrap_or_else(|| Value::Object(Default::default()));
            format!("z.array({})", zod(&item, args))
        }
        "object" => {
            if schema_ir::has_properties(schema) {
                zod_object(schema, args)
            } else if let Some(v) = schema_ir::map_value_schema(schema) {
                format!("z.record({})", zod(v, args))
            } else {
                "z.record(z.unknown())".to_string()
            }
        }
        _ => "z.unknown()".to_string(),
    };
    if matches!(ty, "string" | "integer" | "number" | "array") {
        if let Some(v) = b.min {
            out.push_str(&format!(".min({v})"));
        }
        if let Some(v) = b.max {
            out.push_str(&format!(".max({v})"));
        }
    }
    out
}

/// `z.object({...})`, one `key: <zod>` per property in wire-name order.
pub fn zod_object(schema: &Value, args: bool) -> String {
    let fields = schema_ir::object_fields(schema);
    let mut out = String::from("z.object({");
    for f in &fields {
        // nested objects indent under their key
        let mut e = zod(f.schema, args).replace('\n', "\n  ");
        if !f.required {
            e.push_str(".optional()");
        }
        out.push_str(&format!("\n  {}: {e},", key(f.wire)));
    }
    if !fields.is_empty() {
        out.push('\n');
    }
    out.push_str("})");
    out.push_str(if args && schema_ir::forbids_extra(schema) { ".strict()" } else { ".passthrough()" });
    out
}

/// A JSDoc block for `text`, indented by `ind`.
fn jsdoc(text: &str, ind: &str) -> String {
    let esc = text.replace("*/", "*\\/");
    let mut s = format!("{ind}/**\n");
    for l in esc.lines() {
        let l = l.trim_end();
        if l.is_empty() {
            s.push_str(&format!("{ind} *\n"));
        } else {
            s.push_str(&format!("{ind} * {l}\n"));
        }
    }
    s.push_str(&format!("{ind} */\n"));
    s
}

struct ToolOut {
    name: String,
    description: String,
    base: String,
}

#[derive(Default)]
struct Node {
    children: BTreeMap<String, Node>,
    tools: Vec<(String, usize)>,
}

fn render_ns(out: &mut String, node: &Node, path: &str, tools: &[ToolOut]) -> Result<(), String> {
    for (seg, child) in &node.children {
        render_ns(out, child, &format!("{path}.{seg}"), tools)?;
    }
    let class = format!("Ns{}", camel(path));
    let mut s = format!("export class {class} {{\n");
    for seg in node.children.keys() {
        s.push_str(&format!("  readonly {}: Ns{};\n", key(seg), camel(&format!("{path}.{seg}"))));
    }
    s.push_str("  readonly #c: BaseClient;\n\n  constructor(c: BaseClient) {\n    this.#c = c;\n");
    for seg in node.children.keys() {
        s.push_str(&format!("    {} = new Ns{}(c);\n", member(seg), camel(&format!("{path}.{seg}"))));
    }
    s.push_str("  }\n");
    for (method, idx) in &node.tools {
        let t = &tools[*idx];
        // A tool that is also a family prefix (`host.claim.dns` beside
        // `host.claim.dns.check`) keeps the namespace property; its method
        // takes a trailing underscore, as in the Python SDK (`dns_`).
        let renamed = node.children.contains_key(method);
        let method = &if renamed { format!("{method}_") } else { method.clone() };
        if renamed && (node.children.contains_key(method) || node.tools.iter().any(|(m, _)| m == method)) {
            return Err(format!("{} is both a tool and a family prefix", t.name));
        }
        s.push('\n');
        s.push_str(&jsdoc(&t.description, "  "));
        s.push_str(&format!(
            "  {}(args: s.{}ArgsInput): Promise<s.{}ResultOutput> {{\n    return this.#c.call({}, s.{}Args, s.{}Result, args);\n  }}\n",
            key(method),
            t.base,
            t.base,
            js_str(&t.name),
            t.base,
            t.base
        ));
    }
    s.push_str("}\n\n");
    out.push_str(&s);
    Ok(())
}

/// `this.<seg>` for a bare identifier, `this["seg"]` otherwise.
fn member(seg: &str) -> String {
    let k = key(seg);
    if k.starts_with('"') { format!("this[{k}]") } else { format!("this.{k}") }
}

/// Renders the whole `src/` tree from `contract_bytes`: file name -> contents.
pub fn render(contract_bytes: &[u8]) -> Result<BTreeMap<String, String>, String> {
    let contract: Value = serde_json::from_slice(contract_bytes).map_err(|e| format!("contract is not JSON: {e}"))?;
    let (sha, major, version) = schema_ir::contract_version(&contract, contract_bytes)?;
    let hdr = header(&version);

    let mut schemas = format!("{hdr}import {{ z }} from \"zod\";\n\n");
    let mut tools: Vec<ToolOut> = Vec::new();
    for t in schema_ir::canonical(&contract)? {
        let name = t["name"].as_str().ok_or("tool without a name")?.to_string();
        let base = camel(&name);
        let args = zod_object(&t["input_schema"], true);
        let result = match t.get("output_schema") {
            Some(o) => zod_object(&crate::output_schemas::live_view(o), false),
            None => "z.object({}).passthrough()".to_string(),
        };
        schemas.push_str(&format!(
            "export const {base}Args = {args};\nexport type {base}ArgsInput = z.input<typeof {base}Args>;\n\nexport const {base}Result = {result};\nexport type {base}ResultOutput = z.output<typeof {base}Result>;\n\n"
        ));
        tools.push(ToolOut { name, description: t["description"].as_str().unwrap_or("").to_string(), base });
    }

    let mut files = BTreeMap::new();
    files.insert("schemas.ts".to_string(), schemas.trim_end().to_string() + "\n");
    files.insert("runtime.ts".to_string(), format!("{hdr}{RUNTIME_TS}"));
    files.insert(
        "contract.ts".to_string(),
        format!(
            "{hdr}export const CONTRACT_SHA = {};\nexport const CONTRACT_MAJOR = {};\nexport const CONTRACT_VERSION = {};\n",
            js_str(&sha),
            js_str(&major.to_string()),
            js_str(&version)
        ),
    );

    // errors.ts: header, the shared prelude, one subclass per code, the registry
    let codes = crate::sdk_python::all_error_codes();
    let mut e = format!("{hdr}// error codes: {ERROR_SOURCE}\n{ERRORS_PRELUDE_TS}\n");
    for c in &codes {
        let keys = crate::sdk_python::data_keys_of(c);
        let keys_line = if keys.is_empty() {
            String::new()
        } else {
            let items: Vec<String> = keys.iter().map(|k| js_str(k)).collect();
            format!("  static readonly dataKeys: readonly string[] = [{}];\n", items.join(", "))
        };
        e.push_str(&format!(
            "export class {} extends MCPHostError {{\n{keys_line}  constructor(message: string, data: ErrorData = {{}}) {{\n    super({}, message, data);\n  }}\n}}\n\n",
            camel(c),
            js_str(c)
        ));
    }
    e.push_str("export const ERRORS_BY_CODE: Record<string, new (message: string, data?: ErrorData) => MCPHostError> = {\n");
    for c in &codes {
        e.push_str(&format!("  {}: {},\n", key(c), camel(c)));
    }
    e.push_str("};\n");
    files.insert("errors.ts".to_string(), e);

    // client.ts: family namespaces
    let mut root = Node::default();
    for (i, t) in tools.iter().enumerate() {
        let segs: Vec<&str> = t.name.split('.').collect();
        let (leaf, fam) = segs.split_last().ok_or("empty tool name")?;
        let mut node = &mut root;
        for s in fam {
            node = node.children.entry(ident(s)).or_default();
        }
        node.tools.push((ident(leaf), i));
    }
    if let Some(bad) = root.children.keys().find(|k| CLIENT_MEMBERS.contains(&k.as_str())) {
        return Err(format!("tool family `{bad}` collides with a Client member"));
    }
    let mut c = format!(
        "{hdr}import {{ BaseClient }} from \"./runtime.js\";\nimport type {{ ClientOptions }} from \"./runtime.js\";\nimport * as s from \"./schemas.js\";\n\n"
    );
    for (seg, child) in &root.children {
        render_ns(&mut c, child, seg, &tools)?;
    }
    c.push_str("/** A typed mcphost client; one namespace per tool family (`client.host.tool.publish({...})`). */\nexport class Client extends BaseClient {\n");
    for seg in root.children.keys() {
        c.push_str(&format!("  readonly {}: Ns{};\n", key(seg), camel(seg)));
    }
    c.push_str("\n  constructor(options: ClientOptions) {\n    super(options);\n");
    for seg in root.children.keys() {
        c.push_str(&format!("    {} = new Ns{}(this);\n", member(seg), camel(seg)));
    }
    c.push_str("  }\n}\n");
    files.insert("client.ts".to_string(), c);

    files.insert(
        "index.ts".to_string(),
        format!(
            "{hdr}export * as errors from \"./errors.js\";\nexport {{ CONTRACT_SHA, CONTRACT_VERSION }} from \"./contract.js\";\nexport {{ Client }} from \"./client.js\";\nexport {{ ContractSkew, MCPHostError, ResultShapeError }} from \"./errors.js\";\nexport type {{ ErrorData }} from \"./errors.js\";\nexport type {{ ClientOptions, OnSkew, Skew }} from \"./runtime.js\";\nexport * as schemas from \"./schemas.js\";\n"
        ),
    );
    // every file, schemas.ts included, opens with the header
    Ok(files)
}

/// `mcphost gen sdk ts`: writes the rendered tree into `<out>/src`.
pub fn write(out: &Path, contract_bytes: &[u8]) -> Result<Vec<PathBuf>, String> {
    let files = render(contract_bytes)?;
    let src = out.join("src");
    std::fs::create_dir_all(&src).map_err(|e| format!("create {}: {e}", src.display()))?;
    let mut written = Vec::new();
    for (name, body) in files {
        let p = src.join(&name);
        std::fs::write(&p, body).map_err(|e| format!("write {}: {e}", p.display()))?;
        written.push(p);
    }
    Ok(written)
}
