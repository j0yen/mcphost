//! PRD-mcphost-surface-fluidity requirement 4 (P0, AC5): `www/llms.txt`'s
//! tool list is generated from the same descriptors `tools/list` serves,
//! rather than hand-maintained prose that drifts (the 2026-09-09 audit
//! found 14 documented vs 18 live tenant tools). This module is the pure,
//! synchronous half -- name collection and markdown rendering -- shared by
//! the `mcphost llms-txt` subcommand (`main.rs`) and
//! `tests/surface_ac05_llms_txt_tool_parity.rs`, so neither needs a running
//! server or a DB to exercise it.

use crate::handler::llms_txt_tool_names;
use crate::kinds::KindRegistry;

pub const TOOLS_SECTION_START: &str = "<!-- tools:start -->";
pub const TOOLS_SECTION_END: &str = "<!-- tools:end -->";

pub const CAPABILITIES_SECTION_START: &str = "<!-- capabilities:start -->";
pub const CAPABILITIES_SECTION_END: &str = "<!-- capabilities:end -->";

/// PRD-mcphost-server-capabilities-from-registry requirement 4: the
/// `## Capabilities` section, generated from [`crate::capabilities::CAPABILITIES`]
/// and bracketed by markers so `scripts/sandbox-api-doc-check.sh` can compare
/// it byte-for-byte in `www/llms.txt` and `docs/protocol/capabilities.md`.
/// Table rows (not `- ` bullets): the tools parity test reads bullets as
/// tool names.
pub fn render_capabilities_section() -> String {
    let mut out = String::new();
    out.push_str(CAPABILITIES_SECTION_START);
    out.push_str("\n## Capabilities\n\n");
    out.push_str(
        "Generated by `mcphost capabilities-section` from the `CAPABILITIES` registry -- the same \
         rows `initialize.capabilities` and `GET /capabilities.json` are built from; do not \
         hand-edit. A method of a primitive marked `no` answers `-32601` with `data.help_url` \
         (`/help/capability_unsupported`) and `data.alternative`.\n\n",
    );
    out.push_str("| primitive | implemented | list_changed | probe | alternative | methods |\n");
    out.push_str("|---|---|---|---|---|---|\n");
    for c in crate::capabilities::CAPABILITIES {
        let methods = c.methods.iter().map(|m| format!("`{m}`")).collect::<Vec<_>>().join(", ");
        out.push_str(&format!(
            "| `{}` | {} | {} | `{}` | {} | {} |\n",
            c.name,
            if c.implemented { "yes" } else { "no" },
            if c.list_changed { "yes" } else { "no" },
            c.probe,
            c.alternative.map_or("-".to_string(), |a| format!("`{a}`")),
            methods,
        ));
    }
    out.push_str(CAPABILITIES_SECTION_END);
    out
}

/// The whole of `docs/protocol/capabilities.md`.
pub fn render_capabilities_doc() -> String {
    format!("# MCP capabilities\n\n{}\n", render_capabilities_section())
}

/// Replace the marked capabilities section in `content`, or -- before any
/// marker exists -- insert it just before the `## Contract` heading (else
/// append), so this never drops the section.
pub fn splice_capabilities(content: &str, section: &str) -> String {
    let section = section.trim_end();
    if let (Some(start), Some(end_pos)) = (
        content.find(CAPABILITIES_SECTION_START),
        content.find(CAPABILITIES_SECTION_END),
    ) {
        let end = end_pos + CAPABILITIES_SECTION_END.len();
        format!("{}{}{}", &content[..start], section, &content[end..])
    } else if let Some(idx) = content.find("\n## Contract\n") {
        format!("{}\n{}\n{}", &content[..idx], section, &content[idx..])
    } else {
        format!("{}\n\n{}\n", content.trim_end(), section)
    }
}

pub const IDEMPOTENCY_START: &str = "<!-- idempotency:start -->";
pub const IDEMPOTENCY_END: &str = "<!-- idempotency:end -->";

/// PRD-mcphost-idempotency-key-on-call R7: the `## Idempotency` paragraph,
/// rendered from the `const` strings the dispatch and the `tool_timeout`
/// error use, so the docs cannot drift from the behavior.
pub fn render_idempotency_section() -> String {
    use crate::idempotency::{ARG_KEY, CONFLICT_CODE, CONFLICT_HINT, META_KEY, TIMEOUT_HINT, TTL_SECS};
    format!(
        "{IDEMPOTENCY_START}\n## Idempotency\n\n\
         Any `tools/call` may carry `_meta.{META_KEY}` (or `args.{ARG_KEY}` for clients that drop `_meta`); \
         the host stores the first result for {} h and a repeat with the same key and args returns it with \
         `_meta.replayed: true` without running the tool. The same key with different args answers \
         `{CONFLICT_CODE}` ({CONFLICT_HINT}). A `tool_timeout` error says: {TIMEOUT_HINT}.\n{IDEMPOTENCY_END}",
        TTL_SECS / 3600
    )
}

