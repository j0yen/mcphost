/// PRD-mcphost-server-capabilities-from-registry requirement 4: the
/// `## Capabilities` section, generated from [`crate::capabilities::CAPABILITIES`]
/// and bracketed by markers so `scripts/sandbox-api-doc-check.sh` can compare
/// it byte-for-byte in `www/llms.txt` and `docs/protocol/capabilities.md`.
/// Table rows (not `- ` bullets): the tools parity test reads bullets as
/// tool names.
pub fn render_capabilities_section() -> String {
    let mut out = String::new();
    out.push_str(CAPABILITIES_SECTION_START);
    out.push_str("\n## Capabilities\n\n");
    out.push_str(
        "Generated by `mcphost capabilities-section` from the `CAPABILITIES` registry -- the same \
         rows `initialize.capabilities` and `GET /capabilities.json` are built from; do not \
         hand-edit. A method of a primitive marked `no` answers `-32601` with `data.help_url` \
         (`/help/capability_unsupported`) and `data.alternative`.\n\n",
    );
    out.push_str("| primitive | implemented | list_changed | probe | alternative | methods |\n");
    out.push_str("|---|---|---|---|---|---|\n");
    for c in crate::capabilities::CAPABILITIES {
        let methods = c.methods.iter().map(|m| format!("`{m}`")).collect::<Vec<_>>().join(", ");
        out.push_str(&format!(
            "| `{}` | {} | {} | `{}` | {} | {} |\n",
            c.name,
            if c.implemented { "yes" } else { "no" },
            if c.list_changed { "yes" } else { "no" },
            c.probe,
            c.alternative.map_or("-".to_string(), |a| format!("`{a}`")),
            methods,
        ));
    }
    out.push_str(CAPABILITIES_SECTION_END);
    out
}

/// The whole of `docs/protocol/capabilities.md`.
pub fn render_capabilities_doc() -> String {
    format!("# MCP capabilities\n\n{}\n", render_capabilities_section())
}

