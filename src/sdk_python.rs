//! PRD-mcphost-python-sdk-generated R1/R6: `mcphost gen sdk python` renders
//! the `mcphost_sdk` Python package from `contracts/host-tools.v1.json`.
//!
//! One pydantic v2 `<Tool>Args` / `<Tool>Result` model per canonical tool
//! (`alias_of` entries are skipped), one method per tool grouped into family
//! namespaces by the dotted name, one exception class per error code. The
//! rendering is deterministic (sorted, no timestamps) so CI can regenerate and
//! `diff -r` against the committed tree.
//!
//! Anything the contract expresses that the renderer has to special-case per
//! TOOL goes in [`OVERRIDES`]; the PRD's falsifier is that this table reaches
//! five entries. Per-construct rules (Python-keyword property names get a
//! trailing `_` plus `Field(alias=..)`, `type` lists with `"null"` become
//! `Optional`, `allOf`/`if`/`then` conditionals are server-side validation and
//! are not rendered) are generic and are not overrides.

use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::r#gen::schema_ir::{self, Lit};

/// Default output directory of `mcphost gen sdk python` (the package itself).
pub const DEFAULT_OUT: &str = "sdk/python/mcphost_sdk";

/// `(canonical tool, reason)` pairs the renderer special-cases. Empty: every
/// canonical tool renders through the generic rules. AC1 fails the premise at
/// five entries.
pub const OVERRIDES: &[(&str, &str)] = &[];

const RUNTIME_PY: &str = include_str!("sdk_python_tmpl/runtime.py");
const ERRORS_PRELUDE_PY: &str = include_str!("sdk_python_tmpl/errors_prelude.py");

/// Where the error-code list came from, recorded in `errors.py`'s header
/// (R1). `/errors.json` (PRD-mcphost-errors-json-contract) has not landed and
/// the contract carries no `error_code` enum, so the codes come from the
/// host's own registries.
pub const ERROR_SOURCE: &str = "AppError::code() + feedback::CODE_TO_KIND + feedback::KIND_LEVEL_CODES + error_registry::ERROR_CODES (no /errors.json yet)";

const PY_KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del",
    "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal",
    "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
];

/// Names a generated field/parameter must not take: names the generated
/// modules use in annotations, `BaseModel` attributes, and `self`.
const RESERVED: &[&str] = &[
    "str", "int", "float", "bool", "list", "dict", "set", "tuple", "object", "bytes", "Any", "Optional", "Union",
    "Literal", "Mapping", "Sequence", "Field", "BaseModel", "ConfigDict", "self", "schema", "json", "copy",
    "validate", "construct", "parse_obj", "parse_raw", "parse_file", "from_orm", "update_forward_refs", "Config",
];

fn header(version: &str) -> String {
    format!("# generated by mcphost gen sdk python from contract {version} -- do not edit\n")
}

/// `host.tool_publish` / `args_invalid` -> `HostToolPublish` / `ArgsInvalid`.
pub fn camel(s: &str) -> String {
    s.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut cs = p.chars();
            cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
        })
        .collect()
}

/// A Python identifier for a wire name. Keywords and reserved names get a
/// trailing `_`; punctuation becomes `_`; leading underscores are stripped
/// (pydantic rejects them) and a leading digit is prefixed.
fn py_ident(wire: &str) -> String {
    let mut s: String = wire.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    s = s.trim_start_matches('_').to_string();
    if s.is_empty() {
        s = "field".into();
    }
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        s = format!("f_{s}");
    }
    if PY_KEYWORDS.contains(&s.as_str()) || RESERVED.contains(&s.as_str()) || s.starts_with("model_") {
        s.push('_');
    }
    s
}

fn py_str(s: &str) -> String {
    serde_json::to_string(s).expect("string serializes")
}

fn py_lit(l: &Lit) -> String {
    match l {
        Lit::Str(s) => py_str(s),
        Lit::Bool(b) => if *b { "True" } else { "False" }.into(),
        Lit::Num(n) => n.clone(),
    }
}

/// A docstring body, escaped for a `"""` literal and indented by `ind`.
fn docstring(text: &str, ind: &str) -> String {
    let esc = text.replace('\\', "\\\\").replace("\"\"\"", "\\\"\\\"\\\"");
    let mut lines: Vec<String> = esc.lines().map(|l| l.trim_end().to_string()).collect();
    if lines.is_empty() {
        lines.push(String::new());
    }
    let mut out = String::new();
    for (i, l) in lines.iter().enumerate() {
        out.push_str(if i == 0 { "" } else { ind });
        out.push_str(l);
        out.push('\n');
    }
    // a trailing `"` would merge with the closing quotes
    let body = out.trim_end().to_string();
    let sep = if body.ends_with('"') { " " } else { "" };
    format!("{ind}\"\"\"{body}{sep}\"\"\"\n")
}

/// A rendered type: the annotation used on a model field and the (more
/// permissive) annotation used on a client method parameter.
#[derive(Clone)]
struct Ty {
    field: String,
    param: String,
}

struct Models {
    out: String,
    names: HashSet<String>,
    all: Vec<String>,
}

impl Models {
    fn class_name(&mut self, want: String) -> String {
        let mut name = want;
        while !self.names.insert(name.clone()) {
            name.push('X');
        }
        self.all.push(name.clone());
        name
    }
}

struct Prop {
    wire: String,
    py: String,
    ty: Ty,
    required: bool,
    nullable: bool,
    constraint: String,
}

fn constraints(schema: &Value, only_type: Option<&str>) -> String {
    let Some(t) = only_type else { return String::new() };
    let b = schema_ir::bounds(schema, t);
    let (lo, hi) = match t {
        "integer" | "number" => ("ge", "le"),
        "string" | "array" => ("min_length", "max_length"),
        _ => return String::new(),
    };
    let mut parts = Vec::new();
    if let Some(v) = b.min {
        parts.push(format!("{lo}={v}"));
    }
    if let Some(v) = b.max {
        parts.push(format!("{hi}={v}"));
    }
    parts.join(", ")
}

/// Renders `schema` to a [`Ty`], emitting nested model classes into `m`
/// (children before the parent that uses them). Returns `(ty, nullable)`.
fn render_ty(m: &mut Models, schema: &Value, hint: &str, args: bool) -> (Ty, bool) {
    let (types, nullable) = schema_ir::schema_types(schema);
    if let Some((lits, null)) = schema_ir::enum_values(schema) {
        let t = format!("Literal[{}]", lits.iter().map(py_lit).collect::<Vec<_>>().join(", "));
        return (Ty { field: t.clone(), param: t }, null);
    }
    let mut alts: Vec<Ty> = Vec::new();
    for t in &types {
        alts.push(match *t {
            "string" => Ty { field: "str".into(), param: "str".into() },
            "integer" => Ty { field: "int".into(), param: "int".into() },
            "number" => Ty { field: "float".into(), param: "float".into() },
            "boolean" => Ty { field: "bool".into(), param: "bool".into() },
            "array" => {
                let item = schema.get("items").cloned().unwrap_or(Value::Object(Default::default()));
                let (it, inull) = render_ty(m, &item, &format!("{hint}Item"), args);
                let (f, p) = if inull { (opt(&it.field), opt(&it.param)) } else { (it.field, it.param) };
                Ty { field: format!("list[{f}]"), param: format!("Sequence[{p}]") }
            }
            "object" => {
                if schema_ir::has_properties(schema) {
                    let (class, _) = render_model(m, schema, hint, args);
                    Ty { field: class.clone(), param: format!("Union[{class}, Mapping[str, Any]]") }
                } else if let Some(ap) = schema_ir::map_value_schema(schema) {
                    let (vt, vnull) = render_ty(m, ap, &format!("{hint}Value"), args);
                    let (f, p) = if vnull { (opt(&vt.field), opt(&vt.param)) } else { (vt.field, vt.param) };
                    Ty { field: format!("dict[str, {f}]"), param: format!("Mapping[str, {p}]") }
                } else {
                    Ty { field: "dict[str, Any]".into(), param: "Mapping[str, Any]".into() }
                }
            }
            _ => Ty { field: "Any".into(), param: "Any".into() },
        });
    }
    let ty = match alts.len() {
        0 => Ty { field: "Any".into(), param: "Any".into() },
        1 => alts.remove(0),
        _ => Ty {
            field: format!("Union[{}]", alts.iter().map(|t| t.field.as_str()).collect::<Vec<_>>().join(", ")),
            param: format!("Union[{}]", alts.iter().map(|t| t.param.as_str()).collect::<Vec<_>>().join(", ")),
        },
    };
    (ty, nullable)
}

fn opt(t: &str) -> String {
    if t == "Any" { t.to_string() } else { format!("Optional[{t}]") }
}

fn props_of(m: &mut Models, schema: &Value, class: &str, args: bool) -> Vec<Prop> {
    let mut used = HashSet::new();
    let mut out = Vec::new();
    for f in schema_ir::object_fields(schema) {
        let mut py = py_ident(f.wire);
        while !used.insert(py.clone()) {
            py.push('_');
        }
        let (ty, nullable) = render_ty(m, f.schema, &format!("{class}{}", camel(f.wire)), args);
        let (ts, _) = schema_ir::schema_types(f.schema);
        let only = (ts.len() == 1).then(|| ts[0]);
        out.push(Prop {
            wire: f.wire.to_string(),
            py,
            ty,
            required: f.required,
            nullable,
            constraint: constraints(f.schema, only),
        });
    }
    out
}

/// Emits one model class for an object schema; returns its (deduplicated) name.
fn render_model(m: &mut Models, schema: &Value, hint: &str, args: bool) -> (String, Vec<Prop>) {
    let class = m.class_name(hint.to_string());
    let props = props_of(m, schema, &class, args);
    let forbid = args && schema_ir::forbids_extra(schema);
    let extra = if forbid { "forbid" } else { "allow" };
    let mut body = format!(
        "class {class}(BaseModel):\n    model_config = ConfigDict(extra=\"{extra}\", populate_by_name=True, protected_namespaces=())\n"
    );
    if !props.is_empty() {
        body.push('\n');
    }
    for p in &props {
        body.push_str(&field_line(p));
    }
    m.out.push_str(&body);
    m.out.push_str("\n\n");
    (class, props)
}

fn field_line(p: &Prop) -> String {
    let optional_ann = if p.required && !p.nullable { p.ty.field.clone() } else { opt(&p.ty.field) };
    let mut kw = Vec::new();
    if !(p.required) {
        kw.push("default=None".to_string());
    }
    if p.py != p.wire {
        kw.push(format!("alias={}", py_str(&p.wire)));
    }
    if !p.constraint.is_empty() {
        kw.push(p.constraint.clone());
    }
    if kw.is_empty() {
        format!("    {}: {}\n", p.py, optional_ann)
    } else {
        format!("    {}: {} = Field({})\n", p.py, optional_ann, kw.join(", "))
    }
}

struct ToolOut {
    name: String,
    description: String,
    args_class: String,
    result_class: String,
    params: Vec<Prop>,
}

/// The canonical (non-alias) tool names in `contract_bytes`, sorted.
pub fn canonical_names(contract_bytes: &[u8]) -> Result<Vec<String>, String> {
    schema_ir::canonical_names(contract_bytes)
}

/// The `data` keys the registry declares for `code` beyond the shared
/// envelope ones (empty when none).
pub fn data_keys_of(code: &str) -> &'static [&'static str] {
    crate::error_registry::lookup(code).map_or(&[], |e| e.data_keys)
}

/// Every wire error code the host knows (sorted, deduplicated).
pub fn all_error_codes() -> Vec<String> {
    let mut codes: BTreeSet<String> = crate::errors::all_variants_for_test().iter().map(|e| e.code().to_string()).collect();
    codes.extend(crate::feedback::CODE_TO_KIND.iter().map(|(c, _)| c.to_string()));
    codes.extend(crate::feedback::KIND_LEVEL_CODES.iter().map(|c| c.to_string()));
    // A code declared with `err_code!` outside `AppError` (the sync verbs'
    // `connection_missing`, `quota_syncs_max`, `schedule_too_frequent`) is
    // still one the host returns, so both SDKs get a class for it.
    codes.extend(crate::error_registry::ERROR_CODES.iter().map(|e| e.code.to_string()));
    codes.into_iter().filter(|c| !c.is_empty() && c.chars().all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '_')).collect()
}

#[derive(Default)]
struct Node {
    children: BTreeMap<String, Node>,
    tools: Vec<(String, usize)>,
}

fn render_ns(out: &mut String, node: &Node, path: &str, tools: &[ToolOut]) -> Result<(), String> {
    for (seg, child) in &node.children {
        render_ns(out, child, &format!("{path}.{seg}"), tools)?;
    }
    let class = format!("_Ns{}", camel(path));
    let mut s = format!("class {class}:\n    def __init__(self, c: BaseClient) -> None:\n        self._c = c\n");
    for seg in node.children.keys() {
        let sub = format!("_Ns{}", camel(&format!("{path}.{seg}")));
        s.push_str(&format!("        self.{} = {sub}(c)\n", py_ident(seg)));
    }
    for (method, idx) in &node.tools {
        let t = &tools[*idx];
        // A tool that is also a family prefix (`host.claim.dns` beside
        // `host.claim.dns.check`) keeps the namespace attribute; its method
        // takes a trailing underscore.
        let renamed = node.children.contains_key(method);
        let method = &if renamed { format!("{method}_") } else { method.clone() };
        if renamed && node.tools.iter().any(|(m, _)| m == method) {
            return Err(format!("{} is both a tool and a family prefix", t.name));
        }
        let mut sig = String::from("self, *");
        for p in &t.params {
            let pt = if p.required { if p.nullable { opt(&p.ty.param) } else { p.ty.param.clone() } } else { opt(&p.ty.param) };
            if p.required {
                sig.push_str(&format!(", {}: {pt}", p.py));
            } else {
                sig.push_str(&format!(", {}: {pt} = None", p.py));
            }
        }
        s.push_str(&format!("\n    def {method}({sig}) -> {}:\n", t.result_class));
        s.push_str(&docstring(&t.description, "        "));
        s.push_str("        raw: dict[str, Any] = {");
        s.push_str(&t.params.iter().filter(|p| p.required).map(|p| format!("{}: {}", py_str(&p.py), p.py)).collect::<Vec<_>>().join(", "));
        s.push_str("}\n");
        for p in t.params.iter().filter(|p| !p.required) {
            s.push_str(&format!("        if {} is not None:\n            raw[{}] = {}\n", p.py, py_str(&p.py), p.py));
        }
        s.push_str(&format!(
            "        return self._c._call({}, {}, {}, raw)\n",
            py_str(&t.name),
            t.args_class,
            t.result_class
        ));
    }
    out.push_str(&s);
    out.push_str("\n\n");
    Ok(())
}

/// Renders the whole package from `contract_bytes`: file name -> contents.
pub fn render(contract_bytes: &[u8]) -> Result<BTreeMap<String, String>, String> {
    let contract: Value = serde_json::from_slice(contract_bytes).map_err(|e| format!("contract is not JSON: {e}"))?;
    let (sha, major, version) = schema_ir::contract_version(&contract, contract_bytes)?;
    let hdr = header(&version);

    let mut models = Models { out: String::new(), names: HashSet::new(), all: Vec::new() };
    let mut tools: Vec<ToolOut> = Vec::new();
    for t in schema_ir::canonical(&contract)? {
        let name = t["name"].as_str().ok_or("tool without a name")?.to_string();
        let base = camel(&name);
        let in_schema = &t["input_schema"];
        let (args_class, params) = render_model(&mut models, in_schema, &format!("{base}Args"), true);
        let out_schema = t.get("output_schema").cloned().unwrap_or_else(|| serde_json::json!({"type": "object"}));
        let (result_class, _) = render_model(&mut models, &out_schema, &format!("{base}Result"), false);
        tools.push(ToolOut {
            name,
            description: t["description"].as_str().unwrap_or("").to_string(),
            args_class,
            result_class,
            params,
        });
    }

    let mut files = BTreeMap::new();
    files.insert("py.typed".to_string(), hdr.clone());
    files.insert("_runtime.py".to_string(), format!("{hdr}{RUNTIME_PY}"));
    files.insert(
        "_contract.py".to_string(),
        format!(
            "{hdr}from __future__ import annotations\n\nCONTRACT_SHA = {}\nCONTRACT_MAJOR = {}\nCONTRACT_VERSION = {}\n",
            py_str(&sha),
            py_str(&major.to_string()),
            py_str(&version)
        ),
    );

    let mut m = format!(
        "{hdr}from __future__ import annotations\n\nfrom typing import Any, Literal, Mapping, Optional, Sequence, Union\n\nfrom pydantic import BaseModel, ConfigDict, Field\n\n\n"
    );
    m.push_str(&models.out);
    let mut all = models.all.clone();
    all.sort();
    m.push_str("__all__ = [\n");
    for n in &all {
        m.push_str(&format!("    {},\n", py_str(n)));
    }
    m.push_str("]\n");
    files.insert("models.py".to_string(), m.replace("\n\n\n__all__", "\n\n__all__"));

    // errors.py: header, the shared prelude, one subclass per code, the registry
    let codes = all_error_codes();
    let mut e = format!("{hdr}# error codes: {ERROR_SOURCE}\n{ERRORS_PRELUDE_PY}\n\n");
    for c in &codes {
        let class = camel(c);
        let keys = data_keys_of(c);
        let keys_line = if keys.is_empty() {
            String::new()
        } else {
            let items: Vec<String> = keys.iter().map(|k| py_str(k)).collect();
            format!("    DATA_KEYS: tuple[str, ...] = ({},)\n\n", items.join(", "))
        };
        e.push_str(&format!(
            "class {class}(MCPHostError):\n{keys_line}    def __init__(self, message: str, data: Optional[ErrorData] = None) -> None:\n        super().__init__({}, message, data)\n\n\n",
            py_str(c)
        ));
    }
    e.push_str("ERRORS_BY_CODE: dict[str, type[MCPHostError]] = {\n");
    for c in &codes {
        e.push_str(&format!("    {}: {},\n", py_str(c), camel(c)));
    }
    e.push_str("}\n");
    files.insert("errors.py".to_string(), e);

    // client.py: family namespaces
    let mut root = Node::default();
    for (i, t) in tools.iter().enumerate() {
        let segs: Vec<&str> = t.name.split('.').collect();
        let (leaf, fam) = segs.split_last().ok_or("empty tool name")?;
        let mut node = &mut root;
        for s in fam {
            node = node.children.entry(py_ident(s)).or_default();
        }
        node.tools.push((py_ident(leaf), i));
    }
    let mut c = format!(
        "{hdr}from __future__ import annotations\n\nfrom typing import Any, Literal, Mapping, Optional, Sequence, Union\n\nimport httpx\n\nfrom ._runtime import BaseClient\nfrom .models import *  # noqa: F403\n\n\n"
    );
    for (seg, child) in &root.children {
        render_ns(&mut c, child, seg, &tools)?;
    }
    c.push_str("class Client(BaseClient):\n    \"\"\"A typed mcphost client; one namespace per tool family (`client.host.tool.publish(...)`).\"\"\"\n\n");
    c.push_str(
        "    def __init__(\n        self,\n        url: str,\n        *,\n        key: Optional[str] = None,\n        on_skew: str = \"warn\",\n        timeout: float = 30.0,\n        transport: Optional[httpx.BaseTransport] = None,\n    ) -> None:\n        super().__init__(url, key=key, on_skew=on_skew, timeout=timeout, transport=transport)\n",
    );
    for seg in root.children.keys() {
        c.push_str(&format!("        self.{seg} = _Ns{}(self)\n", camel(seg)));
    }
    files.insert("client.py".to_string(), c);

    files.insert(
        "__init__.py".to_string(),
        format!(
            "{hdr}from . import errors, models\nfrom ._contract import CONTRACT_SHA, CONTRACT_VERSION\nfrom ._runtime import Skew\nfrom .client import Client\nfrom .errors import ContractSkew, ContractSkewWarning, MCPHostError, ResultShapeError\n\n__all__ = [\n    \"CONTRACT_SHA\",\n    \"CONTRACT_VERSION\",\n    \"Client\",\n    \"ContractSkew\",\n    \"ContractSkewWarning\",\n    \"MCPHostError\",\n    \"ResultShapeError\",\n    \"Skew\",\n    \"errors\",\n    \"models\",\n]\n"
        ),
    );
    Ok(files)
}

/// `mcphost gen sdk python`: writes the rendered package into `out`.
pub fn write(out: &Path, contract_bytes: &[u8]) -> Result<Vec<PathBuf>, String> {
    let files = render(contract_bytes)?;
    std::fs::create_dir_all(out).map_err(|e| format!("create {}: {e}", out.display()))?;
    let mut written = Vec::new();
    for (name, body) in files {
        let p = out.join(&name);
        std::fs::write(&p, body).map_err(|e| format!("write {}: {e}", p.display()))?;
        written.push(p);
    }
    Ok(written)
}

#[cfg(test)]
mod all_error_codes_tests {
    use super::all_error_codes;

    /// Every registry code reaches both SDK generators (they share
    /// [`all_error_codes`]), so a code declared with `err_code!` outside
    /// `AppError` cannot be missing from the generated `errors.py` / `errors.ts`.
    #[test]
    fn error_codes_registry_is_a_subset_of_all_error_codes() {
        let all = all_error_codes();
        let missing: Vec<&str> = crate::error_registry::ERROR_CODES
            .iter()
            .map(|e| e.code)
            .filter(|c| !c.is_empty() && !all.iter().any(|a| a == c))
            .collect();
        assert!(missing.is_empty(), "registry codes missing from all_error_codes(): {missing:?}");
    }
}
