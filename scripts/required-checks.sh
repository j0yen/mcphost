#!/usr/bin/env bash
# required-checks.sh -- the required-status-check set is DERIVED from the
# workflow files, never typed into GitHub by hand (PRD-mcphost-msrv-locked-
# required-check; Joe 10-10 "all 9": every context a PR runs).
#
#   --generate   write .github/required-checks.toml from .github/workflows/*.yml
#   --print      print that toml to stdout instead of writing it
#   --check      compare the toml to live branch protection; exit 1 naming each
#                missing context and each stale extra (exit 2: protection
#                unreadable, e.g. no permission)
#   --apply      PATCH live protection's contexts to the toml (operator; admin)
#
# A context is a job's rendered `name:` (the job id when it has none); a
# `strategy.matrix` job expands to one context per combination. Left out:
# jobs whose `if:` restricts them to tags, workflows with no push or
# pull_request trigger, and jobs carrying a `# required-checks: exclude`
# comment line inside their block. Nothing here names a job.
#
# Env: WORKFLOWS_DIR (default .github/workflows), REQUIRED_CHECKS_TOML
# (default .github/required-checks.toml), REQUIRED_CHECKS_JSON (a saved
# `required_status_checks` response, used by --check instead of `gh api`).
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
WORKFLOWS_DIR="${WORKFLOWS_DIR:-.github/workflows}"
TOML="${REQUIRED_CHECKS_TOML:-.github/required-checks.toml}"
export WORKFLOWS_DIR TOML

py() { python3 -I - "$@"; }

render_toml() {
  py <<'PY'
import glob, itertools, os, re, sys
import yaml

MARK = re.compile(r'^\s*#\s*required-checks:\s*exclude\b')
EXPR = re.compile(r'\$\{\{\s*(.*?)\s*\}\}')

def triggers(doc):
    on = doc.get(True, doc.get('on'))  # YAML 1.1 parses bare `on` as True
    if isinstance(on, str):
        return {on}
    if isinstance(on, list):
        return set(on)
    return set(on or {})

def excluded_ids(text):
    """Job ids whose block (indent-2 key to the next) holds the marker."""
    ids, cur, in_jobs = set(), None, False
    for line in text.splitlines():
        if line and not line[0].isspace() and not line.startswith('#'):
            in_jobs = line.startswith('jobs:')
            cur = None
        elif in_jobs:
            m = re.match(r'^  ([A-Za-z0-9_-]+):\s*$', line)
            if m:
                cur = m.group(1)
            elif cur and MARK.match(line):
                ids.add(cur)
    return ids

def render(name, combo):
    def sub(m):
        e = m.group(1)
        mm = re.fullmatch(r'matrix\.(\w+)', e)
        if not mm or mm.group(1) not in combo:
            sys.exit(f"required-checks: cannot render `${{{{ {e} }}}}` in job name {name!r}")
        return str(combo[mm.group(1)])
    return EXPR.sub(sub, name)

contexts = set()
for path in sorted(glob.glob(os.path.join(os.environ['WORKFLOWS_DIR'], '*.y*ml'))):
    text = open(path).read()
    doc = yaml.safe_load(text)
    if not triggers(doc) & {'push', 'pull_request'}:
        continue
    skip = excluded_ids(text)
    for jid, job in (doc.get('jobs') or {}).items():
        cond = str(job.get('if', ''))
        if jid in skip or 'refs/tags/' in cond:
            continue
        name = str(job.get('name', jid))
        matrix = (job.get('strategy') or {}).get('matrix') or {}
        if any(k in matrix for k in ('include', 'exclude')):
            sys.exit(f"required-checks: {path}: job {jid}: matrix include/exclude is not supported")
        keys = [k for k, v in matrix.items() if isinstance(v, list)]
        if not keys:
            contexts.add(render(name, {}))
            continue
        for vals in itertools.product(*(matrix[k] for k in keys)):
            contexts.add(render(name, dict(zip(keys, vals))))

def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

print("# GENERATED by scripts/required-checks.sh --generate from .github/workflows/*.yml -- do not edit.")
print("# Every status context a PR runs. Apply with: scripts/required-checks.sh --apply")
print("contexts = [")
for c in sorted(contexts):
    print(f"  {q(c)},")
print("]")
PY
}

# live contexts (one per line) from REQUIRED_CHECKS_JSON or `gh api`; exit 2 if unreadable
live_json() {
  if [ -n "${REQUIRED_CHECKS_JSON:-}" ]; then
    cat "$REQUIRED_CHECKS_JSON"
  else
    gh api 'repos/{owner}/{repo}/branches/main/protection/required_status_checks' || return 2
  fi
}

case "${1:-}" in
  --generate)
    render_toml > "$TOML.tmp"
    mv "$TOML.tmp" "$TOML"
    echo "required-checks: wrote $TOML ($(grep -c '^  "' "$TOML") contexts)"
    ;;
  --print)
    render_toml
    ;;
  --check)
    json=$(live_json) || { echo "required-checks: cannot read branch protection" >&2; exit 2; }
    LIVE_JSON="$json" py <<'PY'
import json, os, sys, tomllib
want = tomllib.load(open(os.environ['TOML'], 'rb'))['contexts']
live = json.loads(os.environ['LIVE_JSON']).get('contexts') or []
missing = [c for c in want if c not in live]
extra = [c for c in live if c not in want]
for c in missing:
    print(f"required-checks: missing from live protection: {c}")
for c in extra:
    print(f"required-checks: stale extra in live protection: {c}")
if missing or extra:
    print(f"required-checks: {len(missing)} missing, {len(extra)} extra (run --apply)")
    sys.exit(1)
print(f"required-checks: ok ({len(want)} contexts)")
PY
    ;;
  --apply)
    py <<'PY' | gh api -X PATCH 'repos/{owner}/{repo}/branches/main/protection/required_status_checks' --input -
import json, os, tomllib
print(json.dumps({"contexts": tomllib.load(open(os.environ['TOML'], 'rb'))['contexts']}))
PY
    ;;
  *)
    echo "usage: $0 --generate | --print | --check | --apply" >&2
    exit 64
    ;;
esac
