#!/usr/bin/env bash
# gen-agent-docs.sh — README.md and www/llms.txt both carry the agent
# quickstart + measured proof points (PRD-mcphost-agent-findability
# requirement 1: "llms.txt is generated from the same source [as the
# README] so the two cannot drift"). docs/agent-quickstart.md is that one
# source; this script writes its content, byte-for-byte, into the marked
# block in both files.
#
# Usage:
#   scripts/gen-agent-docs.sh          regenerate both marked blocks in place
#   scripts/gen-agent-docs.sh --check  exit 1 if either file's marked block
#                                      is not exactly docs/agent-quickstart.md
#                                      (drift check; wired into CI-equivalent
#                                      local checks the way docs-check.sh is)
set -uo pipefail
cd "$(dirname "$0")/.."

SOURCE="docs/agent-quickstart.md"
START="<!-- agent-quickstart:start -->"
END="<!-- agent-quickstart:end -->"
MODE="${1:-write}"

if [ ! -f "$SOURCE" ]; then
  echo "gen-agent-docs.sh: missing $SOURCE" >&2
  exit 2
fi

# Renders the marked block (including its own markers) for one target file,
# given the marker comment style to use around the shared content. Both
# README.md and www/llms.txt use the same HTML-comment markers so the
# provenance is visible in either file.
render_block() {
  printf '%s\n' "$START"
  cat "$SOURCE"
  printf '%s\n' "$END"
}

# Replaces the text between START and END (inclusive) in $1 with the
# rendered block. Fails loudly if the file has zero or more than one
# start/end marker pair -- this must be mechanical, not best-effort.
apply_to_file() {
  local file="$1"
  local n_start n_end
  n_start=$(grep -Fc "$START" "$file")
  n_end=$(grep -Fc "$END" "$file")
  if [ "$n_start" -ne 1 ] || [ "$n_end" -ne 1 ]; then
    echo "gen-agent-docs.sh: $file must have exactly one $START / $END pair (found start=$n_start end=$n_end)" >&2
    return 2
  fi

  local tmp
  tmp="$(mktemp)"
  python3 - "$file" "$SOURCE" "$START" "$END" > "$tmp" <<'PY'
import sys
file_path, source_path, start_marker, end_marker = sys.argv[1:5]
with open(file_path, encoding="utf-8") as f:
    text = f.read()
with open(source_path, encoding="utf-8") as f:
    source = f.read()

start_idx = text.index(start_marker)
end_idx = text.index(end_marker) + len(end_marker)
old_block = text[start_idx:end_idx]

block = start_marker + "\n" + source.rstrip("\n") + "\n" + end_marker

# Two regions inside the marked block belong to OTHER generators, not to
# docs/agent-quickstart.md, and are carried over from the file as it stands:
#  * README.md "### Sub-agents" recipe (`mcphost llms-txt`, splice_readme_recipe,
#    PRD-mcphost-delegation-recipes-and-quickstart). It cannot live in the source:
#    www/llms.txt gives the same recipe:sub_agent_key markers to a different
#    block, and the llms-txt splice would match the wrong pair.
#  * www/llms.txt domain-hint block (`mcphost llms-txt`,
#    PRD-mcphost-unknown-import-domain-hint).
sub_head = "### Sub-agents\n\n<!-- recipe:sub_agent_key -->"
sub_end = "<!-- /recipe:sub_agent_key -->\n\n"
if sub_head in old_block and sub_end in old_block:
    a = old_block.index(sub_head)
    b = old_block.index(sub_end, a) + len(sub_end)
    region = old_block[a:b]
    anchor = "## Contributing: naming a new"
    if anchor in block:
        i = block.index(anchor)
        block = block[:i] + region + block[i:]
hint_start = "<!-- domain-hint:start -->"
hint_end = "<!-- domain-hint:end -->\n"
if hint_start in old_block and hint_end in old_block:
    a = old_block.index(hint_start)
    b = old_block.index(hint_end, a) + len(hint_end)
    region = old_block[a:b]
    prev_start = old_block.rfind("\n", 0, a - 1) + 1
    prev_line = old_block[prev_start:a]
    if prev_line and block.count(prev_line) == 1:
        i = block.index(prev_line) + len(prev_line)
        block = block[:i] + region + block[i:]
new_text = text[:start_idx] + block + text[end_idx:]
sys.stdout.write(new_text)
PY
  if [ -s "$tmp" ]; then
    mv "$tmp" "$file"
  else
    rm -f "$tmp"
    echo "gen-agent-docs.sh: rendering $file produced no output" >&2
    return 1
  fi
}

check_file() {
  local file="$1"
  local before after orig status
  before="$(mktemp)"
  after="$(mktemp)"
  cp "$file" "$before"
  orig="$(mktemp)"
  cp "$file" "$orig"
  if ! apply_to_file "$file"; then
    rm -f "$before" "$after"
    return 1
  fi
  cp "$file" "$after"
  # The domain-hint block (www/llms.txt) and the "### Sub-agents" recipe
  # (README.md) are generated by `mcphost llms-txt`, not from docs/agent-quickstart.md;
  # apply_to_file carries both over, so neither counts as drift.
  if diff -q "$before" "$after" > /dev/null; then
    status=0
  else
    echo "gen-agent-docs.sh --check: $file is stale against $SOURCE" >&2
    # restore the file: check mode must not leave a write behind
    status=1
  fi
  # check mode must not leave a write behind (even when equal modulo the hint)
  cp "$orig" "$file"
  rm -f "$before" "$after" "$orig"
  return "$status"
}

TARGETS="README.md www/llms.txt"
overall=0

case "$MODE" in
  --check)
    for f in $TARGETS; do
      check_file "$f" || overall=1
    done
    ;;
  write|"")
    for f in $TARGETS; do
      apply_to_file "$f" || overall=1
    done
    ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac

exit "$overall"
