#!/usr/bin/env bash
# gen-codemap.sh -- PRD-mcphost-generated-code-map.
#
# Writes CODEMAP.md at the repo root: one entry per `git ls-files 'src/*.rs'`
# path (in path order) with a size class and the first sentence of its `//!`
# module doc; for files of 2,000+ lines the `// ---- <name> ----` section banner
# names in file order; files of 5,000+ lines with no banner under "Large files
# without sections"; and every top-level `pub static|const NAME: &[...]` array
# registry with its file. No line numbers, so a body-only edit leaves the map
# byte-identical. Needs bash + python3, no cargo.
#
# Usage:
#   scripts/gen-codemap.sh            regenerate CODEMAP.md
#   scripts/gen-codemap.sh --check    exit 1 naming the first differing entry
#                                      if CODEMAP.md is stale; writes nothing
#
# A source file with no `//!` line in its first 5 lines makes either mode exit 2
# naming the file; CODEMAP.md is left untouched.
# CODEMAP_ROOT overrides the repo root (used by the fixture tests).
set -uo pipefail
ROOT="${CODEMAP_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
cd "$ROOT" || exit 2

case "${1:-}" in
  "" | --check) ;;
  *)
    echo "usage: gen-codemap.sh [--check]" >&2
    exit 2
    ;;
esac

exec python3 -I - "${1:-}" <<'PY'
import re
import subprocess
import sys

CHECK = sys.argv[1] == "--check"
OUT = "CODEMAP.md"
SECTION_MIN = 2000
LARGE_MIN = 5000
SUMMARY_MAX = 110

files = subprocess.run(
    ["git", "ls-files", "-z", "src/*.rs"], capture_output=True, check=True
).stdout.decode().split("\0")
files = sorted(f for f in files if f)

BANNER = re.compile(r"^// ---- (.*?)(?:\s+-{2,})?\s*$")
REGISTRY = re.compile(r"^pub (?:static|const) ([A-Za-z0-9_]+)\s*:\s*&\s*(?:'static\s*)?\[")


def clean(text):
    # a `:<digits>` would read as a line reference, which drifts on every commit
    return re.sub(r":(\d)", r" \1", " ".join(text.split()))


def summary(lines):
    head = lines[:5]
    start = next((i for i, l in enumerate(head) if l.startswith("//!")), None)
    if start is None:
        return None
    doc = []
    for l in lines[start:]:
        if not l.startswith("//!"):
            break
        t = l[3:].strip()
        if not t and doc:
            break
        if t:
            doc.append(t)
    text = " ".join(doc)
    m = re.search(r"[.!?](\s|$)", text)
    if m:
        text = text[: m.end()].strip()
    text = clean(text)
    if len(text) > SUMMARY_MAX:
        text = text[: SUMMARY_MAX - 3].rstrip() + "..."
    return text or None


def size_class(n):
    return "<1k" if n < 1000 else f"~{n // 1000}k"


missing = []
entries = []
large = []
registries = []
for path in files:
    with open(path, encoding="utf-8", errors="replace") as fh:
        lines = fh.read().splitlines()
    doc = summary(lines)
    if doc is None:
        missing.append(path)
        continue
    banners = []
    if len(lines) >= SECTION_MIN:
        for l in lines:
            m = BANNER.match(l)
            if m and m.group(1).strip():
                banners.append(clean(m.group(1)))
        if not banners and len(lines) >= LARGE_MIN:
            large.append(path)
    for l in lines:
        m = REGISTRY.match(l)
        if m:
            registries.append((path, m.group(1)))
    entries.append((path, size_class(len(lines)), doc, banners))

if missing:
    for p in missing:
        print(f"gen-codemap.sh: {p} has no `//!` module doc in its first 5 lines", file=sys.stderr)
    sys.exit(2)

out = [
    "# CODEMAP",
    "",
    "GENERATED by scripts/gen-codemap.sh from the source tree -- do not edit.",
    "Regenerate with `scripts/gen-codemap.sh`; CI runs `scripts/gen-codemap.sh --check`.",
    "Size class is the file's line count rounded down to thousands. To jump to a",
    "section of a big file: grep -n '^// ---- <name>' <file>.",
    "",
    "## Files",
    "",
]
for path, size, doc, banners in entries:
    out.append(f"- `{path}` ({size}) {doc}")
    if banners:
        out.append("  - sections: " + " | ".join(banners))
out += ["", "## Large files without sections", ""]
out += [f"- `{p}`" for p in large] or ["- (none)"]
out += ["", "## Registries", ""]
out += [f"- `{name}` in `{path}`" for path, name in sorted(registries)] or ["- (none)"]
text = "\n".join(out) + "\n"

if CHECK:
    try:
        have = open(OUT, encoding="utf-8").read()
    except FileNotFoundError:
        have = ""
    if have == text:
        sys.exit(0)
    old, new = have.splitlines(), text.splitlines()
    ent = re.compile(r"^- `([^`]+)`")
    paths = lambda ls: {m.group(1) for l in ls if (m := ent.match(l))}
    added, removed = sorted(paths(new) - paths(old)), sorted(paths(old) - paths(new))
    if added:
        what = f"entry added: {added[0]}"
    elif removed:
        what = f"entry removed: {removed[0]}"
    else:
        i = next((i for i in range(max(len(old), len(new))) if (old[i] if i < len(old) else None) != (new[i] if i < len(new) else None)), 0)
        what = "first differing line: " + (new[i] if i < len(new) else old[i])
    print(f"gen-codemap.sh --check: {OUT} is stale ({what}); run scripts/gen-codemap.sh", file=sys.stderr)
    sys.exit(1)

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write(text)
PY
