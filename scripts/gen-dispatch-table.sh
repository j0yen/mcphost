#!/usr/bin/env bash
# gen-dispatch-table.sh -- PRD-mcphost-generated-dispatch-table-stack-budget R1.
#
# `src/dispatch_table.rs` is the verb table `dispatch_tenant_tool_inner` looks a
# dotted host verb up in: one row per canonical dotted `host.*` verb the
# descriptor registry advertises (`mcphost contract dump`, minus the entries
# that carry `alias_of`), sorted, each row naming the function `arm_<verb>`
# (`host.calls.list` -> `arm_host_calls_list`) in `src/handler/arms.rs`. The
# verb set is GENERATED from the registry, never listed by hand: a row without
# a function fails `cargo check`, a function without a row fails
# `tests/fwdtab_ac02_*`.
#
# Usage:
#   scripts/gen-dispatch-table.sh --write   regenerate src/dispatch_table.rs
#   scripts/gen-dispatch-table.sh --check   exit 1, naming src/dispatch_table.rs,
#                                           if it differs from what the registry
#                                           generates now (writes nothing)
#
# Reads the registry through the built binary (target/debug/mcphost, built here
# if absent); `regen-check` builds it once for every generator.
set -uo pipefail
cd "$(dirname "$0")/.."

MODE="${1:---check}"
TARGET="src/dispatch_table.rs"
BIN="${MCPHOST_BIN:-target/debug/mcphost}"

case "$MODE" in
  --check | --write) ;;
  *)
    echo "usage: gen-dispatch-table.sh --check|--write" >&2
    exit 2
    ;;
esac

if [ ! -x "$BIN" ]; then
  cargo build --locked --bin mcphost >&2 || exit 2
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
"$BIN" contract dump --path "$work/contract.json" >/dev/null || {
  echo "gen-dispatch-table.sh: $BIN contract dump failed" >&2
  exit 2
}

python3 -I - "$work/contract.json" >"$work/dispatch_table.rs" <<'PY' || exit 2
import json, sys

tools = json.load(open(sys.argv[1]))["tools"]
verbs = sorted(
    {t["name"] for t in tools if t["name"].startswith("host.") and "alias_of" not in t}
)
if not verbs:
    sys.exit("gen-dispatch-table.sh: the contract names no canonical host.* verb")
print("//! Generated verb-to-arm dispatch table for the canonical dotted `host.*` verbs.")
print()
print("// GENERATED by scripts/gen-dispatch-table.sh from `mcphost contract dump` (the")
print("// canonical dotted `host.*` descriptors, aliases excluded). Do not edit: change the")
print("// descriptor registry or `src/handler/arms.rs`, then run the script with --write.")
print("//")
print("// PRD-mcphost-generated-dispatch-table-stack-budget R1: one sorted row per verb,")
print("// each naming the `arm_<verb>` function that builds that verb's future on the heap.")
print()
print("use crate::handler::{ArmCtx, ArmFut, McpHostHandler};")
print()
print("/// One verb's arm: a function returning its future already pinned on the heap.")
print("pub type Arm = for<'a> fn(&'a McpHostHandler, ArmCtx<'a>) -> ArmFut<'a>;")
print()
print("/// Every canonical dotted `host.*` verb and its arm, sorted by name.")
print("pub const DISPATCH_TABLE: &[(&str, Arm)] = &[")
for v in verbs:
    print(f'    ("{v}", McpHostHandler::arm_{v.replace(".", "_")}),')
print("];")
print()
print("/// The arm for `name`, if it is a canonical dotted `host.*` verb.")
print("pub fn lookup(name: &str) -> Option<Arm> {")
print("    DISPATCH_TABLE")
print("        .binary_search_by(|(verb, _)| (*verb).cmp(name))")
print("        .ok()")
print("        .map(|i| DISPATCH_TABLE[i].1)")
print("}")
print()
print("/// The verb names, in table order.")
print("pub fn names() -> Vec<&'static str> {")
print("    DISPATCH_TABLE.iter().map(|(verb, _)| *verb).collect()")
print("}")
PY

if [ "$MODE" = "--write" ]; then
  cp "$work/dispatch_table.rs" "$TARGET"
  echo "gen-dispatch-table.sh: wrote $TARGET ($(grep -c '^    ("' "$TARGET") rows)"
  cargo check --locked --lib >&2 || {
    echo "gen-dispatch-table.sh: cargo check failed; a row names an arm_* function that does not exist in src/handler/arms.rs" >&2
    exit 1
  }
  exit 0
fi

if ! cmp -s "$work/dispatch_table.rs" "$TARGET"; then
  echo "gen-dispatch-table.sh: $TARGET is stale (the descriptor registry changed without a regen): run scripts/gen-dispatch-table.sh --write" >&2
  diff -u "$TARGET" "$work/dispatch_table.rs" 2>&1 | head -20 >&2
  exit 1
fi
echo "gen-dispatch-table.sh: $TARGET is up to date"
