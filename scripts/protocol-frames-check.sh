#!/usr/bin/env bash
# protocol-frames-check.sh -- PRD-mcphost-sse-frame-contract-generated R3/R6.
# The frames the host may emit per request type are ONE Rust table
# (`FRAME_SEQUENCES` in src/protocol/frames.rs). This script parses that table
# back out of the Rust source text (never a second hand-kept list) and renders
#   docs/protocol/frames.md   the table, for humans
#   www/frames.json  the same rows, for the probe (GET /protocol/frames.json)
#   www/llms.txt              the Transport block between the frames markers
#
# Usage:
#   scripts/protocol-frames-check.sh --check          exit 0, or exit 1 naming each drifted file
#   scripts/protocol-frames-check.sh --write          regenerate all three
#   scripts/protocol-frames-check.sh --render-llms    print the llms.txt Transport block
set -uo pipefail
cd "$(dirname "$0")/.."

MODE="${1:---check}"
case "$MODE" in
  --check | --write | --render-llms) ;;
  *) echo "usage: protocol-frames-check.sh [--check|--write|--render-llms]" >&2; exit 2 ;;
esac

exec python3 - "$MODE" <<'PY'
import json
import re
import sys

MODE = sys.argv[1]
SOURCE = "src/protocol/frames.rs"
DOC = "docs/protocol/frames.md"
JSON_FILE = "www/frames.json"
LLMS = "www/llms.txt"
START = "<!-- frames:start -->"
END = "<!-- frames:end -->"
AFTER = "<!-- capabilities:end -->"
# content type per frame count, for each ContentTypeRule variant
RULE_TYPES = {"JsonWhenSingleFrame": ("application/json", "text/event-stream")}


def die(msg):
    print("protocol-frames-check.sh: " + msg, file=sys.stderr)
    sys.exit(2)


try:
    with open(SOURCE, encoding="utf-8") as f:
        src = f.read()
except OSError:
    die("missing " + SOURCE)

methods = dict(re.findall(r'FrameKind::(\w+) => "([^"]+)",', src))
notation = dict(re.findall(r'Card::(\w+) => "([^"]+)",', src))
rule_names = dict(re.findall(r'ContentTypeRule::(\w+) => "([^"]+)",', src))
version = re.search(r'pub const PROTOCOL_VERSION: &str = "([^"]+)";', src)
timing_header = re.search(r'pub const SERVER_TIMING_HEADER: &str = "([^"]+)";', src)
timing_metric = re.search(r'pub const SERVER_TIMING_METRIC: &str = "([^"]+)";', src)
block = re.search(r"pub const FRAME_SEQUENCES: &\[FrameRow\] = &\[(.*?)\n\];", src, re.S)
if not (methods and notation and rule_names and version and block and timing_header and timing_metric):
    die("could not find FrameKind::method, Card::notation, ContentTypeRule::name, PROTOCOL_VERSION, SERVER_TIMING_HEADER, SERVER_TIMING_METRIC or FRAME_SEQUENCES in " + SOURCE)

TIMING = (
    "Every `/mcp` response carries `%s: %s;dur=<ms>`: the host's wall time from the request reaching the route "
    "(auth and rate-limit time included) to the response head being ready, so a `text/event-stream` response reports time to "
    "response head, not to its last frame. Caddy, TLS and network time are not included."
) % (timing_header.group(1), timing_metric.group(1))

rows = []
for rt, frames, rule in re.findall(
    r'FrameRow \{\s*request_type: "([^"]+)",\s*frames: &\[(.*?)\],\s*content_type_rule: ContentTypeRule::(\w+),\s*\}',
    block.group(1),
    re.S,
):
    if rule not in RULE_TYPES or rule not in rule_names:
        die("unknown content_type_rule " + rule)
    pairs = re.findall(r"\(FrameKind::(\w+), Card::(\w+)\)", frames)
    rows.append((rt, [(methods[k], notation[c]) for k, c in pairs], rule))
if not rows:
    die("FRAME_SEQUENCES has no rows")


def card(c):
    return "{" + c + "}"


def render_md():
    out = [
        "# Response frames per request type",
        "",
        "Generated by `scripts/protocol-frames-check.sh` from `FRAME_SEQUENCES` in `src/protocol/frames.rs`; do not hand-edit.",
        "",
        "Protocol version: `%s`. A response is one JSON-RPC document unless a frame precedes the result on the same request, in which case it upgrades to `text/event-stream` carrying every frame in order. `{1}` = exactly one, `{0,1}` = optional, `{0,n}` = any number.",
        "",
        TIMING,
        "",
        "| request type | frames in order | content type |",
        "|---|---|---|",
    ]
    out[4] = out[4] % version.group(1)
    for rt, frames, rule in rows:
        one, many = RULE_TYPES[rule]
        seq = ", ".join("`%s` %s" % (m, card(c)) for m, c in frames)
        out.append("| `%s` | %s | `%s` with one frame, `%s` with more (`%s`) |" % (rt, seq, one, many, rule_names[rule]))
    return "\n".join(out) + "\n"


def render_json():
    doc = {
        "generated_from": SOURCE + "::FRAME_SEQUENCES",
        "protocol_version": version.group(1),
        "server_timing": {
            "header": timing_header.group(1),
            "metric": timing_metric.group(1),
            "unit": "ms",
            "semantics": TIMING,
        },
        "rows": [
            {
                "request_type": rt,
                "frames": [{"method": m, "card": card(c)} for m, c in frames],
                "content_type": {
                    "rule": rule_names[rule],
                    "single_frame": RULE_TYPES[rule][0],
                    "multi_frame": RULE_TYPES[rule][1],
                },
            }
            for rt, frames, rule in rows
        ],
    }
    return json.dumps(doc, indent=2) + "\n"


def render_llms():
    parts = []
    for rt, frames, _ in rows:
        parts.append("`%s` = %s" % (rt, ", ".join("`%s` %s" % (m, card(c)) for m, c in frames)))
    return "\n".join(
        [
            START,
            "## Transport",
            "",
            "Generated by `scripts/protocol-frames-check.sh` from `FRAME_SEQUENCES`; do not hand-edit. A response is `application/json` when it is one frame and `text/event-stream` when more than one frame is sent (`{1}` exactly one, `{0,1}` optional, `{0,n}` any number). Take the last `result` or `error` frame. Per request type, in order: "
            + "; ".join(parts)
            + ". "
            + TIMING
            + " Machine-readable: [/protocol/frames.json](/protocol/frames.json).",
            END,
        ]
    ) + "\n"


def read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        return None


def llms_with_block(text):
    block_text = render_llms()
    if START in text and END in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1]
        return head + block_text.rstrip("\n") + tail
    if AFTER not in text:
        die("%s has neither the frames markers nor %s to insert after" % (LLMS, AFTER))
    head, tail = text.split(AFTER, 1)
    return head + AFTER + "\n\n" + block_text.rstrip("\n") + tail


if MODE == "--render-llms":
    sys.stdout.write(render_llms())
    sys.exit(0)

llms_text = read(LLMS)
if llms_text is None:
    die("missing " + LLMS)
wanted = {DOC: render_md(), JSON_FILE: render_json(), LLMS: llms_with_block(llms_text)}

if MODE == "--write":
    import os

    for path, content in wanted.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if read(path) != content:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            print("protocol-frames-check.sh: wrote " + path)
    sys.exit(0)

drift = [p for p, content in wanted.items() if read(p) != content]
for p in drift:
    print("protocol-frames-check.sh: DRIFT %s differs from FRAME_SEQUENCES (run scripts/protocol-frames-check.sh --write)" % p, file=sys.stderr)
sys.exit(1 if drift else 0)
PY
